import numpy as np
import pandas as pd
from statsmodels.stats.diagnostic import acorr_ljungbox
from statsmodels.sandbox.stats.runs import runstest_1samp

np.random.seed(12)
T = 500

def simulate_garch_innovations(n, omega=0.01, alpha=0.1, beta=0.85):
    eps = np.zeros(n)
    sigma2 = np.zeros(n)
    sigma2[0] = omega / (1 - alpha - beta)
    for t in range(1, n):
        sigma2[t] = omega + alpha * eps[t - 1] ** 2 + beta * sigma2[t - 1]
        eps[t] = np.sqrt(sigma2[t]) * np.random.normal()
    return eps / np.sqrt(sigma2)  # standardized residuals

# Three types of noise
gaussian_wn = np.random.normal(0, 1, T)
uniform_wn = np.random.uniform(-np.sqrt(3), np.sqrt(3), T)  # var=1
garch_noise = simulate_garch_innovations(T)

for name, series in [("Gaussian WN", gaussian_wn),
                     ("Uniform WN", uniform_wn),
                     ("GARCH Std Resid", garch_noise)]:
    print(f"\n{'='*50}")
    print(f"Series: {name}")

    # Ljung-Box on levels
    lb = acorr_ljungbox(series, lags=[10, 20], return_df=True)
    print(f"Ljung-Box (lags 10,20) p-values: {lb['lb_pvalue'].values}")

    # Ljung-Box on squares (ARCH effects)
    lb_sq = acorr_ljungbox(series ** 2, lags=[10, 20], return_df=True)
    print(f"Ljung-Box on SQUARES (lags 10,20) p-values: {lb_sq['lb_pvalue'].values}")

    # Runs test
    z_stat, p_val = runstest_1samp(series, correction=False)
    print(f"Runs test p-value: {p_val:.4f}")

