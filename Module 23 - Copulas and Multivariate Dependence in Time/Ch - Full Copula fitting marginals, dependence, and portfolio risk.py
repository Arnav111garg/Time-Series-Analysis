def portfolio_var_mc(copula, n_sim=100000, horizon=1, weights=None):
    """Monte Carlo portfolio VaR using copula."""
    if weights is None:
        weights = np.ones(d) / d

    # Simulate copula
    if copula == 'gaussian':
        R = np.eye(d)
        idx = 0
        for i in range(d):
            for j in range(i + 1, d):
                R[i, j] = R[j, i] = rho_gaussian[idx]
                idx += 1
        L = np.linalg.cholesky(R)
        Z = np.random.normal(0, 1, (n_sim, d))
        Z = Z @ L.T
        U_sim = stats.norm.cdf(Z)
    elif copula == 't':
        R = np.eye(d)
        idx = 0
        for i in range(d):
            for j in range(i + 1, d):
                R[i, j] = R[j, i] = rho_t[idx]
                idx += 1
        L = np.linalg.cholesky(R)
        Z = np.random.normal(0, 1, (n_sim, d))
        Z = Z @ L.T
        chi2_rv = np.random.chisquare(nu_t, n_sim) / nu_t
        Z = Z / np.sqrt(chi2_rv[:, None])
        U_sim = stats.t.cdf(Z, df=nu_t)
    else:
        raise ValueError(f"Unknown copula: {copula}")

    # Transform back to returns using empirical marginal CDFs
    port_rets = np.zeros(n_sim)
    for k in range(d):
        # Empirical quantile of uniform draws
        marg_ret = np.quantile(ret.iloc[:, k].values, U_sim[:, k])
        port_rets += weights[k] * marg_ret
    return np.sort(port_rets)

