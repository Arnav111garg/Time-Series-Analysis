def gaussian_copula_loglik(rho_params, U):
    """Log-likelihood of Gaussian copula with correlation matrix."""
    d = U.shape[1]
    T = U.shape[0]
    # Build correlation matrix from rho_params (lower triangle)
    R = np.eye(d)
    idx = 0
    for i in range(d):
        for j in range(i + 1, d):
            R[i, j] = R[j, i] = np.tanh(rho_params[idx])
            idx += 1
    # Check positive definiteness
    try:
        np.linalg.cholesky(R)
    except np.linalg.LinAlgError:
        return 1e10
    # Transform U to Z (normal scores)
    Z = stats.norm.ppf(np.clip(U, 1e-10, 1 - 1e-10))
    # Copula log-likelihood
    R_inv = np.linalg.inv(R)
    sign, log_det = np.linalg.slogdet(R)
    if sign <= 0:
        return 1e10
    quad = np.einsum('ti,ij,tj->t', Z, R_inv - np.eye(d), Z)
    ll = -0.5 * T * log_det - 0.5 * np.sum(quad)
    return -ll

def student_t_copula_loglik(params, U):
    """Student-t copula log-likelihood."""
    d = U.shape[1]
    T = U.shape[0]
    n_rho = d * (d - 1) // 2
    rho_params = params[:n_rho]
    log_nu = params[n_rho]
    nu = np.exp(log_nu) + 2  # ensure nu > 2

    R = np.eye(d)
    idx = 0
    for i in range(d):
        for j in range(i + 1, d):
            R[i, j] = R[j, i] = np.tanh(rho_params[idx])
            idx += 1
    try:
        np.linalg.cholesky(R)
    except np.linalg.LinAlgError:
        return 1e10

    Z = stats.t.ppf(np.clip(U, 1e-10, 1 - 1e-10), df=nu)
    R_inv = np.linalg.inv(R)
    sign, log_det = np.linalg.slogdet(R)
    if sign <= 0:
        return 1e10

    ll = 0
    from scipy.special import gammaln
    for t in range(T):
        z = Z[t]
        quad = z @ R_inv @ z
        # d-variate t log-density
        log_pdf_mv = (gammaln((nu + d) / 2) - gammaln(nu / 2)
                      - 0.5 * d * np.log(nu * np.pi) - 0.5 * log_det
                      - (nu + d) / 2 * np.log(1 + quad / nu))
        # Marginal t log-densities
        log_pdf_margin = np.sum([np.log(stats.t.pdf(z[k], df=nu) + 1e-300)
                                 for k in range(d)])
        ll += log_pdf_mv - log_pdf_margin
    return -ll

def clayton_copula_cdf(U, theta):
    """Clayton copula CDF."""
    d = U.shape[1] if len(U.shape) > 1 else len(U)
    if theta <= 0:
        return np.prod(U, axis=-1)
    inner = np.sum(U**(-theta) - 1, axis=-1)
    return np.maximum((1 + inner)**(-1 / theta), 0)

def gumbel_copula_cdf(U, theta):
    """Gumbel copula CDF (2D)."""
    assert U.shape[1] == 2 and theta >= 1
    u1, u2 = U[:, 0], U[:, 1]
    t1 = (-np.log(np.maximum(u1, 1e-10)))**theta
    t2 = (-np.log(np.maximum(u2, 1e-10)))**theta
    return np.exp(-((t1 + t2)**(1 / theta)))

