import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from statsmodels.tsa.ar_model import AutoReg
from statsmodels.tsa.statespace.sarimax import SARIMAX
from statsmodels.graphics.tsaplots import plot_acf, plot_pacf
from statsmodels.stats.diagnostic import acorr_ljungbox
import yfinance as yf

# Simulating AR(2)
np.random.seed(12)
T = 500
phi1, phi2, sigma = 0.6, -0.2, 1.0

X = np.zeros(T)
eps = np.random.normal(0, sigma, T)
for t in range(2, T):
    X[t] = phi1 * X[t - 1] + phi2 * X[t - 2] + eps[t]

# Fit AR(2) via OLS using AutoReg
ar2_fit = AutoReg(X, lags=2).fit()
print(ar2_fit.summary())
print(f"\nTrue params: phi1={phi1}, phi2={phi2}, sigma={sigma}")
print(f"Estm params: phi1={ar2_fit.params[1]:.4f}, phi2={ar2_fit.params[2]:.4f}")

# Residual diagnostics
resid = ar2_fit.resid
lb = acorr_ljungbox(resid, lags=[10, 20], return_df=True)
print(f"\nLjung-Box on residuals:\n{lb}")

# Stationarity check via roots
# AR(2) characteristic polynomial: 1 - phi1 * z - phi2 * z^2 = 0
roots = np.roots([-phi2, -phi1, 1])  # numpy: highest degree first
print(f"\nCharacteristic roots: {roots}")
print(f"Moduli: {np.abs(roots)}")
print(f"Stationary: {all(np.abs(roots) > 1)}")

# Impulse Response Function
def ar_irf(params, horizon=20):
    p = len(params)
    psi = np.zeros(horizon + 1)
    psi[0] = 1.0
    for h in range(1, horizon + 1):
        psi[h] = sum(params[j] * psi[h - 1 - j] for j in range(min(h, p)))
    return psi

irf = ar_irf([phi1, phi2], horizon=20)
plt.figure(figsize=(12, 5))
plt.stem(range(21), irf, markerfmt='C0o', linefmt='C0-', basefmt='k-')
plt.axhline(0, color='black', linewidth=0.8)
plt.xlabel("Horizon (h)")
plt.ylabel(r"$\psi_h$")
plt.title(rf"AR(2) Impulse Response: $\phi_1={phi1}$, $\phi_2={phi2}$")
plt.tight_layout()
plt.savefig("ar2_irf.pdf", dpi=150)
plt.show()

# Forecasting
n_forecast = 20

# Use SARIMAX for proper forecast intervals
model_sm = SARIMAX(X, order=(2, 0, 0)).fit(disp=False)
fc = model_sm.get_forecast(steps=n_forecast)
fc_mean = fc.predicted_mean
fc_ci = fc.conf_int(alpha=0.05)

plt.figure(figsize=(12, 5))
t_idx = np.arange(T)
plt.plot(t_idx[-100:], X[-100:], 'navy', label='Data')
plt.plot(np.arange(T, T + n_forecast), fc_mean, 'r--', label='Forecast')
plt.fill_between(np.arange(T, T + n_forecast), fc_ci[:, 0], fc_ci[:, 1], alpha=0.25, color='red', label='95% CI')
plt.legend()
plt.tight_layout()
plt.savefig("ar2_forecast.pdf", dpi=150)
plt.show()

