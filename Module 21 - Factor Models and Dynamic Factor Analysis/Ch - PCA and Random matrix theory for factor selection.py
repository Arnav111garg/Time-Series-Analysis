import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler

# Download S&P 500 constituent returns
# Use a representative set of liquid stocks
tickers_sp500 = [
    'AAPL', 'MSFT', 'NVDA', 'GOOGL', 'AMZN', 'META', 'TSLA', 'BRK-B', 'JPM', 'JNJ',
    'V', 'PG', 'MA', 'HD', 'CVX', 'MRK', 'ABBV', 'PEP', 'KO', 'AVGO', 'LLY',
    'TMO', 'COST', 'MCD', 'ABT', 'ACN', 'DHR', 'NKE', 'TXN', 'CMCSA', 'NFLX',
    'WMT', 'DIS', 'UNH', 'CRM', 'QCOM', 'INTC', 'AMD', 'AMAT', 'MU', 'ADI',
    'LRCX', 'KLAC', 'TER', 'ON', 'SNPS', 'CDNS', 'ANSS', 'SWKS', 'MCHP'
]

print("Downloading stocks...")
raw = yf.download(tickers_sp500, start='2015-01-01', end='2024-01-01', auto_adjust=True)

# Handle MultiIndex columns if present in yfinance output
if isinstance(raw.columns, pd.MultiIndex):
    # Extract only the Close prices
    raw = raw['Close']

raw = raw.dropna(axis=1, thresh=int(0.9 * len(raw)))
ret = np.log(raw / raw.shift(1)).dropna()
print(f"Returns matrix: {ret.shape[0]} days x {ret.shape[1]} stocks")

N, T = ret.shape[1], ret.shape[0]

# Standardize returns
scaler = StandardScaler()
ret_std = scaler.fit_transform(ret)

# PCA
pca = PCA()
pca.fit(ret_std)
eigenvalues = pca.explained_variance_

print(f"\nTop 10 eigenvalues:")
for i, ev in enumerate(eigenvalues[:10]):
    print(f" PC{i+1}: {ev:.4f} ({ev/eigenvalues.sum() * 100:.1f}% variance explained)")

cum_var = np.cumsum(pca.explained_variance_ratio_)
print(f"\nFactors to explain 50% of variance: {np.searchsorted(cum_var, 0.5)+1}")
print(f"Factors to explain 70% of variance: {np.searchsorted(cum_var, 0.7)+1}")
print(f"Factors to explain 90% of variance: {np.searchsorted(cum_var, 0.9)+1}")

# Random Matrix Theory: Marchenko-Pastur upper bound
q = T / N  # ratio T/N
sigma2 = 1.0  # standardized returns
lambda_plus = sigma2 * (1 + np.sqrt(1/q))**2  # upper edge
lambda_minus = sigma2 * (1 - np.sqrt(1/q))**2  # lower edge

print(f"\nMarchenko-Pastur bounds (N={N}, T={T}, q={q:.2f}):")
print(f" Lower edge: {lambda_minus:.4f}")
print(f" Upper edge: {lambda_plus:.4f}")
print(f" Significant factors (eigenvalue > {lambda_plus:.4f}): {np.sum(eigenvalues > lambda_plus)}")

# Marchenko-Pastur density
def marchenko_pastur_pdf(x, q, sigma2=1.0):
    """Marchenko-Pastur density at x."""
    l_plus = sigma2 * (1 + np.sqrt(1/q))**2
    l_minus = sigma2 * (1 - np.sqrt(1/q))**2
    if x < l_minus or x > l_plus:
        return 0
    return (q / (2 * np.pi * sigma2)) * np.sqrt((l_plus - x) * (x - l_minus)) / x

x_grid = np.linspace(max(0.001, lambda_minus - 0.1), lambda_plus + 0.5, 500)
mp_pdf = np.array([marchenko_pastur_pdf(xi, q) for xi in x_grid])

# Visualization
fig, axes = plt.subplots(1, 3, figsize=(16, 5))
fig.suptitle("PCA and Random Matrix Theory Analysis of S&P 500 Returns", fontsize=12, fontweight='bold')

# 1. Eigenvalue spectrum
n_bins = 50
axes[0].hist(eigenvalues, bins=n_bins, density=True, color='steelblue', alpha=0.7, label='Empirical eigenvalues', edgecolor='none')
axes[0].plot(x_grid, mp_pdf, 'red', lw=2.5, label=f'Marchenko-Pastur (q={q:.2f})')
axes[0].axvline(lambda_plus, color='darkorange', lw=2.5, linestyle='--', label=f'Upper edge: {lambda_plus:.2f}')
axes[0].set_xlim(0, lambda_plus * 3)
axes[0].set_xlabel("Eigenvalue")
axes[0].set_ylabel("Density")
axes[0].set_title("Eigenvalue Spectrum vs Marchenko-Pastur")
axes[0].legend(fontsize=9)

# Mark significant eigenvalues
sig_mask = eigenvalues > lambda_plus
n_sig = sig_mask.sum()
for ev in eigenvalues[sig_mask]:
    axes[0].axvline(ev, color='green', lw=1, alpha=0.5)
axes[0].text(0.65, 0.95, f'{n_sig} significant\nfactors (RMT)', transform=axes[0].transAxes, fontsize=10, bbox=dict(facecolor='white', alpha=0.8))

# 2. Explained variance
k_max = 30
axes[1].bar(range(1, k_max+1), eigenvalues[:k_max] / eigenvalues.sum() * 100,
           color=['green' if eigenvalues[i] > lambda_plus else 'steelblue' for i in range(k_max)],
           alpha=0.8, edgecolor='none')
axes[1].plot(range(1, k_max+1), np.cumsum(eigenvalues[:k_max]) / eigenvalues.sum() * 100, 'k-o', markersize=4, label='Cumulative')
axes[1].axhline(70, color='r', lw=1, linestyle='--', label='70%')
axes[1].set_xlabel("Principal Component")
axes[1].set_ylabel("Variance Explained (%)")
axes[1].set_title("Scree Plot (Green = RMT significant)")
axes[1].legend()

# 3. First 3 PC loadings
for pc_num, col in zip([0, 1, 2], ['navy', 'firebrick', 'darkgreen']):
    sorted_idx = np.argsort(pca.components_[pc_num])
    axes[2].plot(range(N), pca.components_[pc_num][sorted_idx], color=col, lw=1.5, alpha=0.8, label=f'PC{pc_num+1}')
axes[2].axhline(0, color='k', lw=0.5)
axes[2].set_xlabel("Stock (sorted by PC1 loading)")
axes[2].set_ylabel("Loading")
axes[2].set_title("Factor Loadings: PC1-3")
axes[2].legend()

plt.tight_layout()
plt.savefig("pca_rmt_sp500.pdf", dpi=150)
plt.show()

# Factor-based covariance estimate
r_factors = np.searchsorted(np.cumsum(eigenvalues) / eigenvalues.sum(), 0.7) + 1
print(f"\nUsing r={r_factors} factors to explain 70% of variance")

pca_r = PCA(n_components=r_factors)
F_hat = pca_r.fit_transform(ret_std)  # T x r factor scores
L_hat = pca_r.components_.T  # N x r loadings (scaled)

# Factor model covariance (shrinkage toward factor structure)
Sigma_factor = L_hat @ np.diag(pca_r.explained_variance_) @ L_hat.T
Psi_hat = np.diag(np.diag(np.cov(ret_std.T) - Sigma_factor))
Psi_hat = np.maximum(Psi_hat, 0)  # ensure non-negative
Sigma_fm = Sigma_factor + Psi_hat

print(f"\nFactor model covariance matrix computed: {Sigma_fm.shape}")
print(f" Condition number: {np.linalg.cond(Sigma_fm):.1f}")
print(f" (Full sample cov condition: {np.linalg.cond(np.cov(ret_std.T)):.1f})")

