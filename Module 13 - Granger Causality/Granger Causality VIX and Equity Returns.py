import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
import pandas_datareader as pdr
from statsmodels.tsa.stattools import grangercausalitytests, adfuller
from statsmodels.tsa.api import VAR
import warnings
warnings.filterwarnings('ignore')

def get_yf_series(ticker, start, end):
    # Download single ticker raw data
    df_raw = yf.download(ticker, start=start, end=end, progress=False)

    # Flatten MultiIndex columns if present (e.g. ('Adj Close', 'SPY') -> 'Adj Close')
    if isinstance(df_raw.columns, pd.MultiIndex):
        cols = [c[0] for c in df_raw.columns]
        df_flat = df_raw.copy()
        df_flat.columns = cols
    else:
        df_flat = df_raw

    # Extract key series (fallback to Close if Adj Close is missing)
    for col in ['Adj Close', 'Close']:
        if col in df_flat.columns:
            series = df_flat[col]
            # Handle potential duplicate column names after flattening
            if isinstance(series, pd.DataFrame):
                return series.iloc[:, 0].dropna()
            return series.dropna()

    raise KeyError(f"Could not find Close or Adj Close for {ticker}")

# Data: VIX, SPX returns, Credit Spread
spy = get_yf_series("SPY", start="2003-01-01", end="2024-01-01")
vix = pdr.get_data_fred("VIXCLS", start="2003-01-01", end="2024-01-01")
hyg = get_yf_series("HYG", start="2007-07-01", end="2024-01-01")
lqd = get_yf_series("LQD", start="2007-07-01", end="2024-01-01")

spy_ret = 100 * np.log(spy / spy.shift(1)).dropna()
vix_chg = vix.diff().dropna()
hy_oas = 100 * np.log(hyg / lqd).diff().dropna()  # proxy for HY-IG spread change

# Align and merge
df = pd.DataFrame({
    'SPY_ret': spy_ret,
    'VIX_chg': vix_chg.squeeze(),
    'HY_spread_chg': hy_oas
}).dropna()

print(f"Dataset shape: {df.shape}")
print(df.head())

# Unit root tests
for col in df.columns:
    p = adfuller(df[col], autolag='BIC')[1]
    print(f"ADF {col}: p={p:.4f} ({'stationary' if p < 0.05 else 'unit root'})")

print("\n" + "=" * 60)
print("GRANGER CAUSALITY TESTS (max lag = 5)")
print("=" * 60)

pairs = [
    ('SPY_ret', 'VIX_chg', "Does SPX return Granger-cause VIX change?"),
    ('VIX_chg', 'SPY_ret', "Does VIX change Granger-cause SPX return?"),
    ('HY_spread_chg', 'SPY_ret', "Does HY spread Granger-cause SPX return?"),
    ('SPY_ret', 'HY_spread_chg', "Does SPX return Granger-cause HY spread?"),
    ('VIX_chg', 'HY_spread_chg', "Does VIX Granger-cause HY spread?"),
 ]

gc_summary = []
for cause, effect, description in pairs:
    print(f"\n{description}")
    data_pair = df[[effect, cause]].dropna()  # NOTE: order matters! y, x
    gc = grangercausalitytests(data_pair, maxlag=5)
    for lag, test_dict in gc.items():
        f_stat = test_dict[0]['ssr_ftest'][0]
        f_p = test_dict[0]['ssr_ftest'][1]
        chi2 = test_dict[0]['lrtest'][0]
        chi2_p = test_dict[0]['lrtest'][1]
        signif = '***' if f_p < 0.01 else '**' if f_p < 0.05 else '*' if f_p < 0.10 else ''
        print(f"  Lag {lag}: F={f_stat:.3f} (p={f_p:.4f}), LR chi2={chi2:.3f} (p={chi2_p:.4f}) {signif}")
        gc_summary.append({'cause': cause, 'effect': effect, 'lag': lag, 'F': f_stat, 'p': f_p})

gc_df = pd.DataFrame(gc_summary)
print("\n=== SUMMARY: Minimum p-value across lags ===")
print(gc_df.groupby(['cause', 'effect'])['p'].min().unstack())

# VAR-based joint Granger causality
print("\n=== VAR-based Granger Causality (joint lags 1-5) ===")
var_model = VAR(df).fit(maxlags=5, ic='bic')
print(var_model.summary())

# Block exogeneity test (Granger causality in VAR)
print("\n=== Block Exogeneity Tests ===")
for cause in df.columns:
    for effect in df.columns:
        if cause != effect:
            test_res = var_model.test_causality(caused=effect, causing=cause, kind='f')
            is_sig = 'SIGNIFICANT' if test_res.pvalue < 0.05 else ''
            print(f"{cause} -> {effect}: F={test_res.test_statistic:.4f}, p={test_res.pvalue:.4f} {is_sig}")

# Visualize Granger causality network
import matplotlib.patches as mpatches
import matplotlib.patheffects as pe

fig, ax = plt.subplots(figsize=(10, 8))
ax.set_xlim(-2, 2)
ax.set_ylim(-2, 2)
ax.set_aspect('equal')
ax.axis('off')
ax.set_title("Granger Causality Network\n(arrows = significant at 5% level, by minimum p-value across 5 lags)", fontsize=12, fontweight='bold')

nodes = {'SPY_ret': (0, 1.5), 'VIX_chg': (-1.2, -0.8), 'HY_spread_chg': (1.2, -0.8)}
colors = ['#2196F3', '#F44336', '#4CAF50']
for (name, pos), col in zip(nodes.items(), colors):
    circle = plt.Circle(pos, 0.38, color=col, zorder=5, alpha=0.8)
    ax.add_patch(circle)
    ax.text(pos[0], pos[1], name.replace('_', '\n'), ha='center', va='center', fontsize=9, fontweight='bold', color='white', zorder=6)

min_p = gc_df.groupby(['cause', 'effect'])['p'].min()
for (cause, effect), p in min_p.items():
    if p < 0.05:
        x0, y0 = nodes[cause]
        x1, y1 = nodes[effect]
        dx, dy = x1 - x0, y1 - y0
        norm = np.sqrt(dx**2 + dy**2)
        r = 0.40
        ax.annotate("", xy=(x1 - r * dx / norm, y1 - r * dy / norm),
                    xytext=(x0 + r * dx / norm, y0 + r * dy / norm),
                    arrowprops=dict(arrowstyle='->', color='black', lw=2.5 * (1 - p + 0.05), mutation_scale=20))
        mid_x = (x0 + x1) / 2 + 0.15 * (-dy / norm)
        mid_y = (y0 + y1) / 2 + 0.15 * (dx / norm)
        ax.text(mid_x, mid_y, f'p={p:.3f}', fontsize=8, ha='center', va='center',
                bbox=dict(facecolor='white', alpha=0.7, edgecolor='none'))

plt.tight_layout()
plt.savefig("granger_causality_network.pdf", dpi=150)
plt.show()

