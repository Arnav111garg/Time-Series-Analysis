import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from scipy.optimize import minimize
from arch import arch_model

# Data
spy_df = yf.download("SPY", start="2000-01-01", end="2024-01-01")
spy = spy_df["Close"].squeeze()
ret = 100 * np.log(spy / spy.shift(1)).dropna()  # in percent


# A. GARCH(1,1) from scratch via numerical MLE
def garch11_filter(params, returns):
    """Compute GARCH(1,1) conditional variances via recursion."""
    omega, alpha, beta = params
    T = len(returns)
    sigma2 = np.zeros(T)
    sigma2[0] = np.var(returns)  # initialize at sample variance
    for t in range(1, T):
        sigma2[t] = omega + alpha * returns[t - 1] ** 2 + beta * sigma2[t - 1]
    return sigma2

def garch11_loglik(params, returns):
    """Negative Gaussian log-likelihood for GARCH(1,1)."""
    omega, alpha, beta = params
    if omega <= 0 or alpha < 0 or beta < 0 or alpha + beta >= 1:
        return 1e10
    sigma2 = garch11_filter(params, returns)
    if np.any(sigma2 <= 0):
        return 1e10
    T = len(returns)
    ll = -0.5 * np.sum(np.log(2 * np.pi) + np.log(sigma2) + returns**2 / sigma2)
    return -ll  # minimize negative log-likelihood

r = ret.values
x0 = [0.05, 0.08, 0.90]
bounds = [(1e-6, None), (1e-6, 1), (1e-6, 1)]
result = minimize(garch11_loglik, x0, args=(r,),
                  method='L-BFGS-B', bounds=bounds,
                  options={'maxiter': 5000})

omega_hat, alpha_hat, beta_hat = result.x
print(f"Manual MLE: omega={omega_hat:.6f}, alpha={alpha_hat:.4f}, beta={beta_hat:.4f}")
print(f"Persistence (alpha+beta): {alpha_hat+beta_hat:.4f}")
print(f"Unconditional vol (ann): {np.sqrt(omega_hat / (1 - alpha_hat - beta_hat)) * np.sqrt(252):.2f}%")
print(f"Half-life (days): {-np.log(2) / np.log(alpha_hat+beta_hat):.1f}")

# B. Using the `arch` package (production-grade)
# Gaussian GARCH(1,1)
garch_normal = arch_model(ret, vol='GARCH', p=1, q=1, dist='normal')
res_normal = garch_normal.fit(disp='off')

# Student-t GARCH(1,1)
garch_t = arch_model(ret, vol='GARCH', p=1, q=1, dist='t')
res_t = garch_t.fit(disp='off')

# Skewed-t GARCH(1,1)
garch_skewt = arch_model(ret, vol='GARCH', p=1, q=1, dist='skewt')
res_skewt = garch_skewt.fit(disp='off')

print("\nModel Comparison:")
print(f"GARCH-Normal AIC: {res_normal.aic:.2f}, BIC: {res_normal.bic:.2f}")
print(f"GARCH-t AIC: {res_t.aic:.2f}, BIC: {res_t.bic:.2f}")
print(f"GARCH-Skew-t AIC: {res_skewt.aic:.2f}, BIC: {res_skewt.bic:.2f}")
print(res_t.summary())

# C. Visualize conditional volatility
cond_vol = res_t.conditional_volatility * np.sqrt(252)  # annualize

fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(14, 8), sharex=True)
ax1.plot(ret.index, ret, color='navy', linewidth=0.5, alpha=0.7)
ax1.set_ylabel("Log Return (%)")
ax1.set_title("SPY Daily Returns")

ax2.plot(cond_vol.index, cond_vol, color='firebrick', linewidth=0.8)
ax2.set_ylabel("Conditional Vol (Ann. %)")
ax2.set_title("GARCH(1,1)-t Conditional Volatility")
ax2.axhline(cond_vol.mean(), color='k', linestyle='--', label=f'Mean: {cond_vol.mean():.1f}%')
ax2.legend()

plt.tight_layout()
plt.savefig("garch11_condvol.pdf", dpi=150)

# D. GARCH forecasting
fc = res_t.forecast(horizon=22)  # 22-day ahead forecast
fc_var = fc.variance.iloc[-1]  # variance forecasts h=1..22
fc_vol = np.sqrt(fc_var) * np.sqrt(252)

plt.figure(figsize=(14, 8))
plt.plot(range(1, 23), fc_vol.values, 'r-o', markersize=4, label='GARCH(1,1)-t Forecast')
plt.axhline(cond_vol.iloc[-1], color='navy', linestyle='--', label=f'Current vol: {cond_vol.iloc[-1]:.1f}%')
plt.axhline(np.sqrt(res_t.params['omega'] / (1 - res_t.params['alpha[1]'] - res_t.params['beta[1]'])) * np.sqrt(252),
            color='green', linestyle=':', label='Unconditional vol')
plt.xlabel("Horizon (trading days)")
plt.ylabel("Forecast Ann. Vol (%)")
plt.title("GARCH(1,1)-t Volatility Forecast (22-day)")
plt.legend()
plt.tight_layout()
