from statsmodels.stats.diagnostic import acorr_ljungbox, het_arch
from scipy import stats

std_resid = res_t.resid / res_t.conditional_volatility

print("\nGARCH(1,1)-t Diagnostic Suite")
print("=" * 50)

# 1. Ljung-Box on std residuals
lb = acorr_ljungbox(std_resid.dropna(), lags=[10, 20], return_df=True)
print(f"Ljung-Box on z_t (p-values): {lb['lb_pvalue'].values}")

# 2. Ljung-Box on squared std residuals
lb2 = acorr_ljungbox(std_resid.dropna()**2, lags=[10, 20], return_df=True)
print(f"Ljung-Box on z_t^2 (p-values): {lb2['lb_pvalue'].values}")

# 3. ARCH-LM
arch_stat, arch_p, _, _ = het_arch(std_resid.dropna(), nlags=10)
print(f"ARCH-LM test p-value: {arch_p:.4f}")

# 4. Normality of std residuals
jb_stat, jb_p = stats.jarque_bera(std_resid.dropna())
print(f"Jarque-Bera p-value: {jb_p:.6f}")
print(f"Skewness: {std_resid.skew():.4f}, Kurtosis: {std_resid.kurtosis() + 3:.4f}")

# 5. Sign bias test (simplified)
z = std_resid.dropna()
z_neg = (z < 0).astype(float)
z_pos = (z > 0).astype(float)
from statsmodels.regression.linear_model import OLS
from statsmodels.tools import add_constant
X_sb = add_constant(pd.DataFrame({
    'I_neg': z_neg.shift(1),
    'z_neg': (z.shift(1) * (z.shift(1) < 0)),
    'z_pos': (z.shift(1) * (z.shift(1) > 0))
}).dropna())
y_sb = (z**2).iloc[1:]
sb_reg = OLS(y_sb, X_sb).fit()
print(f"\nSign Bias Test F-statistic: {sb_reg.fvalue:.4f}, p-value: {sb_reg.f_pvalue:.4f}")
print("(p < 0.05 suggests need for asymmetric model)")

