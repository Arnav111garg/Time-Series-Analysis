import pandas as pd
import numpy as np
import yfinance as yf
from statsmodels.tsa.stattools import adfuller, kpss

aapl = yf.download("AAPL", start="2015-01-01", end="2024-01-01", auto_adjust=False)["Adj Close"]
log_aapl = np.log(aapl)
ret_aapl = log_aapl.diff().dropna()

def run_unit_root_suite(series, name):
    print(f"\n{'='*60}")
    print(f"Unit Root Test Suite: {name}")
    print('='*60)

    # ADF Test
    adf_stat, adf_p, adf_lags, _, crit_vals, _ = adfuller(series, autolag='AIC', regression='ct')
    print(f"\n [ADF Test] H0: unit root")
    print(f" Statistic: {adf_stat:.4f}")
    print(f" p-value: {adf_p:.4f}")
    print(f" Lags used: {adf_lags}")
    print(f" Crit vals: {crit_vals}")
    print(f" Decision: {'REJECT H0 (Stationary)' if adf_p < 0.05 else 'FAIL TO REJECT (Likely unit root)'}")

    # KPSS Test
    kpss_stat, kpss_p, kpss_lags, kpss_crit = kpss(series, regression='ct', nlags='auto')
    print(f"\n [KPSS Test] H0: stationary")
    print(f" Statistic: {kpss_stat:.4f}")
    print(f" p-value: {kpss_p:.4f} (interpolated)")
    print(f" Lags used: {kpss_lags}")
    print(f" Crit vals: {kpss_crit}")
    print(f" Decision: {'REJECT H0 (Non-stationary)' if kpss_p < 0.05 else 'FAIL TO REJECT (Likely stationary)'}")

run_unit_root_suite(log_aapl, "Log AAPL Price")
run_unit_root_suite(ret_aapl, "AAPL Log Returns")

