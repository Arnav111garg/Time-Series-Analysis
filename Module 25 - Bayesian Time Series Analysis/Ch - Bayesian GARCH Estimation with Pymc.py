# Posterior predictive next-day vol
axes[2, 0].hist(vol_pred, bins=60, density=True, color='darkorange', alpha=0.7, edgecolor='none')
axes[2, 0].axvline(vol_pred.mean(), color='red', lw=2, label=f'Mean: {vol_pred.mean():.1f}%')
ci_vol = np.percentile(vol_pred, [2.5, 97.5])
axes[2, 0].axvspan(ci_vol[0], ci_vol[1], alpha=0.2, color='darkorange')
axes[2, 0].set_title("Posterior Predictive: Next-Day Ann. Vol (%)")
axes[2, 0].set_xlabel("Volatility (% ann.)")
axes[2, 0].legend()

# Joint posterior
axes[2, 1].scatter(posterior[:, 1], posterior[:, 2], s=1.5, alpha=0.2, color='navy')
axes[2, 1].contourf(*(np.mgrid[posterior[:, 1].min():posterior[:, 1].max():50j, posterior[:, 2].min():posterior[:, 2].max():50j]),
                     np.histogram2d(posterior[:, 1], posterior[:, 2], bins=50)[0].T, levels=10, alpha=0.4, cmap='Blues')
