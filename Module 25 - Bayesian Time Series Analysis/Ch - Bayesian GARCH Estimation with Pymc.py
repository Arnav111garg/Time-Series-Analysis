# METHOD 1: MANUAL BAYESIAN GARCH VIA METROPOLIS-HASTINGS
#

def garch11_loglik(params, returns):
    """GARCH(1,1) log-likelihood."""
    omega, alpha, beta = params
    if omega <= 0 or alpha < 0 or beta < 0 or alpha + beta >= 1:
        return -np.inf
    T = len(returns)
    sigma2 = np.zeros(T)
    sigma2[0] = np.var(returns)
    for t in range(1, T):
        sigma2[t] = omega + alpha * returns[t - 1] ** 2 + beta * sigma2[t - 1]
        if sigma2[t] <= 0:
            return -np.inf
    ll = -0.5 * np.sum(np.log(2 * np.pi * sigma2) + returns**2 / sigma2)
    return ll

def log_prior(params):
    """Log-prior for GARCH(1,1) parameters."""
    omega, alpha, beta = params
    if omega <= 0 or alpha < 0 or beta < 0 or alpha + beta >= 1:
        return -np.inf
    # Weakly informative priors
    # omega ~ HalfNormal(0.1)
    # alpha ~ Beta(2, 10) -> favors small alpha
    # beta ~ Beta(10, 2) -> favors large beta (persistence)
    from scipy.stats import halfnorm, beta as beta_dist
    lp = halfnorm.logpdf(omega, scale=0.1)
    lp += beta_dist.logpdf(alpha, a=2, b=10)
    lp += beta_dist.logpdf(beta, a=10, b=2)
    return lp

def log_posterior(params, returns):
    """Log-posterior = log-likelihood + log-prior."""
    lp = log_prior(params)
    if not np.isfinite(lp):
        return -np.inf
    ll = garch11_loglik(params, returns)
    return ll + lp

# Metropolis-Hastings
np.random.seed(2024)
n_samples = 15000
n_burnin = 5000
step_sizes = np.array([0.002, 0.008, 0.008])  # per-parameter step sizes

# Initialize at MLE
from scipy.optimize import minimize
def neg_ll(p): return -garch11_loglik(p, r_arr)
x0 = [0.05, 0.08, 0.88]
res = minimize(neg_ll, x0, method='L-BFGS-B', bounds=[(1e-6, 1), (0, 1), (0, 1)])
theta_curr = res.x.copy()
print(f"\nMLE starting point: omega={theta_curr[0]:.6f}, alpha={theta_curr[1]:.4f}, beta={theta_curr[2]:.4f}")

samples = np.zeros((n_samples, 3))
lp_curr = log_posterior(theta_curr, r_arr)
n_accept = 0

print("Running Metropolis-Hastings MCMC...")
for s in range(n_samples):
    # Random walk proposal
    theta_prop = theta_curr + np.random.normal(0, step_sizes)
    lp_prop = log_posterior(theta_prop, r_arr)

    # Accept / reject
    log_ratio = lp_prop - lp_curr
    if np.log(np.random.uniform()) < log_ratio:
        theta_curr = theta_prop
        lp_curr = lp_prop
        n_accept += 1

    samples[s] = theta_curr

    if (s + 1) % 2500 == 0:
        accept_rate = n_accept / (s + 1)
        print(f"Iteration {s+1}/{n_samples}, acceptance rate: {accept_rate:.3f}")

# Discard burn-in
posterior = samples[n_burnin:]
print(f"\nPosterior samples: {len(posterior)} (after {n_burnin} burn-in)")

# Effective sample size
def effective_sample_size(chain):
    """Approximate ESS using autocorrelation."""
    T = len(chain)
    acf_sum = 0
    for k in range(1, T):
        rho_k = np.corrcoef(chain[:-k], chain[k:])[0, 1]
        if abs(rho_k) < 0.05:  # cutoff when ACF is small
            break
        acf_sum += rho_k
    return T / (1 + 2 * acf_sum)

print(f"\nBayesian GARCH(1,1) Posterior Summary:")
print(f"{'Parameter':<12} {'MLE':>10} {'Post. Mean':>12} {'Post. Std':>10} {'95% CI':>20} {'ESS':>8}")
print('-' * 78)
param_names = ['omega', 'alpha', 'beta']
mle_vals = res.x

for i, (name, mle) in enumerate(zip(param_names, mle_vals)):
    chain = posterior[:, i]
    pmean = chain.mean()
    pstd = chain.std()
    pci = np.percentile(chain, [2.5, 97.5])
    ess = effective_sample_size(chain)
    print(f"{name:<12} {mle:>10.6f} {pmean:>12.6f} {pstd:>10.6f} [ {pci[0]:>8.6f} , {pci[1]:>8.6f} ] {ess:>8.0f}")

persistence_post = posterior[:, 1] + posterior[:, 2]
print(f"\nPersistence alpha+beta:")
print(f"  MLE: {mle_vals[1] + mle_vals[2]:.4f}")
print(f"  Post. Mean: {persistence_post.mean():.4f}")
print(f"  Post. Std: {persistence_post.std():.4f}")
print(f"  P(alpha+beta > 0.99): {(persistence_post > 0.99).mean():.4f}")

# Posterior predictive
print("\nComputing posterior predictive distribution for next-day vol...")
vol_pred = np.zeros(len(posterior))
for i, (omega, alpha, beta) in enumerate(posterior):
    s2 = np.var(r_arr[:10])
    for t in range(1, T):
        s2 = omega + alpha * r_arr[t - 1] ** 2 + beta * s2
    vol_pred[i] = np.sqrt(s2 * 252)  # annualized

# Visualization
fig, axes = plt.subplots(3, 3, figsize=(15, 12))
fig.suptitle("Bayesian GARCH(1,1): Posterior Analysis", fontsize=13, fontweight='bold')

# Trace plots
for i, (name, ax) in enumerate(zip(param_names, axes[0])):
    ax.plot(posterior[:, i], 'navy', lw=0.4, alpha=0.7)
    ax.axhline(posterior[:, i].mean(), color='red', lw=1.5, linestyle='--')
    ax.set_title(f"Trace plot: {name}")
    ax.set_xlabel("MCMC Iteration")
    ax.set_ylabel(name)

# Posterior histograms
for i, (name, ax) in enumerate(zip(param_names, axes[1])):
    ax.hist(posterior[:, i], bins=60, density=True, color='steelblue', alpha=0.7, edgecolor='none')
    ax.axvline(posterior[:, i].mean(), color='red', lw=2, label=f'Mean: {posterior[:, i].mean():.4f}')
    ax.axvline(mle_vals[i], color='green', lw=2, linestyle='--', label=f'MLE: {mle_vals[i]:.4f}')
    ci = np.percentile(posterior[:, i], [2.5, 97.5])
