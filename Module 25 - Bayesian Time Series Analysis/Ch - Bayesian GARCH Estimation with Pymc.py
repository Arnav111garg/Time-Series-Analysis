import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
import warnings
warnings.filterwarnings('ignore')

# Download data (handling potential yfinance MultiIndex or missing 'Adj Close' column)
df = yf.download("SPY", start="2018-01-01", end="2026-01-01")

# Safely extract adjusted close or close price
if isinstance(df.columns, pd.MultiIndex):
    if "Adj Close" in df.columns.get_level_values(0):
        spy = df["Adj Close"]["SPY"]
    else:
        spy = df["Close"]["SPY"]
else:
    if "Adj Close" in df.columns:
        spy = df["Adj Close"]
    else:
        spy = df["Close"]

r = 100 * np.log(spy / spy.shift(1)).dropna()
r_arr = r.values
T = len(r_arr)
print(f"Using {T} daily SPY returns for Bayesian GARCH")

