import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import pandas_datareader as pdr
from statsmodels.tsa.vector_ar.vecm import VECM, coint_johansen
from statsmodels.tsa.stattools import adfuller
import warnings
warnings.filterwarnings('ignore')

# Data: 2Y and 10Y Treasury yields
yields_raw = pdr.get_data_fred(['GS2', 'GS10'], start='1990-01-01', end='2024-01-01')
yields_raw = yields_raw.dropna()
yields_raw.columns = ['y2Y', 'y10Y']
data = yields_raw[['y10Y', 'y2Y']] # ordering matters for normalization

print("Data shape: ", data.shape)
print(data.tail())

# Unit root tests
for col in data.columns:
    p = adfuller(data[col], regression='ct', autolag='BIC')[1]
    print(f"ADF ({col}): p={p:.4f} ({'I(1) candidate' if p > 0.05 else 'I(0)'})")

# Johansen test to determine rank
print("\n=== Johansen Cointegration Test ===")
johansen = coint_johansen(data, det_order=0, k_ar_diff=2)
print("Eigenvalues: ", np.round(johansen.eig, 6))
print("\nTrace Statistics (H0: r<=0, r<=1, ...)")
for i, (tr, cv) in enumerate(zip(johansen.lr1, johansen.cvt)):
    print(f"  r<={i}: Trace={tr:.4f}, Crit(5%)={cv[1]:.4f} -> {'Reject H0' if tr > cv[1] else 'Fail to Reject'}")

print("\nMax-Eigenvalue Statistics:")
for i, (mx, cv) in enumerate(zip(johansen.lr2, johansen.cvm)):
    print(f"  r={i}: MaxEig={mx:.4f}, Crit(5%)={cv[1]:.4f} -> {'Reject H0' if mx > cv[1] else 'Fail to Reject'}")

print("\nCointegrating Vectors:")
beta_df = pd.DataFrame(johansen.evec, index=data.columns, columns=[f'CV{i+1}' for i in range(len(data.columns))])
print(beta_df)

# Normalize: first CV normalized to [1, -beta2]
cv1 = johansen.evec[:, 0]
beta_norm = -cv1[1] / cv1[0]
print(f"\nNormalized cointegrating vector: y10Y - {beta_norm:.4f}*y2Y = 0")

spread = data['y10Y'] - beta_norm * data['y2Y']
print(f"Spread stats: mean={spread.mean():.4f}, std={spread.std():.4f}")
print(f"ADF on spread: p={adfuller(spread, autolag='BIC')[1]:.4f}")

# Fit VECM
vecm = VECM(data, k_ar_diff=2, coint_rank=1, deterministic='co')
vecm_fit = vecm.fit()
print("\n=== VECM Fit Summary ===")
print(vecm_fit.summary())

# Extract alpha and beta
alpha = vecm_fit.alpha
beta = vecm_fit.beta
print(f"\nLoading matrix (alpha):")
print(pd.DataFrame(alpha, index=data.columns, columns=['EC1']))
print(f"\nCointegrating matrix (beta):")
print(pd.DataFrame(beta, index=data.columns, columns=['CV1']))

print(f"\nAlpha interpretation:")
for col, a in zip(data.columns, alpha[:, 0]):
    print(f"  {col}: alpha={a:.4f} -> {'corrects toward equil.' if a < 0 else 'moves away from equil.'}")
print(f"  Speed of adjustment: {abs(alpha[:, 0]).mean():.4f} per day")
print(f"  Mean reversion half-life: ~{np.log(2) / abs(alpha[:, 0].mean()):.0f} days")

# VECM-based spread trading signal (calculated manually as beta is fitted with the constant)
# beta contains coefficients for [y10Y, y2Y] and potentially deterministic terms if specified inside
beta_y = beta[:, 0]
ect = data.values @ beta_y
ect_series = pd.Series(ect, index=data.index)

fig, axes = plt.subplots(3, 1, figsize=(10, 6), sharex=True)

axes[0].plot(data['y10Y'], 'navy', lw=0.8, label='10Y Yield')
axes[0].plot(data['y2Y'], 'firebrick', lw=0.8, label='2Y Yield')
axes[0].legend()
axes[0].set_ylabel('Yield (%)')
axes[0].set_title("US Treasury Yields: 2Y and 10Y")

axes[1].plot(spread, 'purple', lw=0.7, label='Spread')
axes[1].axhline(spread.mean(), color='k', lw=0.8, linestyle='--')
axes[1].fill_between(spread.index, spread, spread.mean(),
                     where=(spread > spread.mean()),
                     color='red', alpha=0.2, label='Above mean')
axes[1].fill_between(spread.index, spread, spread.mean(),
                     where=(spread < spread.mean()),
                     color='green', alpha=0.2, label='Below mean')
axes[1].legend()
axes[1].set_title("Cointegrating Spread (y10Y - beta*y2Y)")

# VECM forecasts
fc = vecm_fit.predict(steps=63) # 3-month forecast
fc_df = pd.DataFrame(fc, columns=data.columns, index=pd.date_range(data.index[-1], periods=63+1, freq='B')[1:])
for col, color in zip(data.columns, ['navy', 'firebrick']):
    axes[0].plot(fc_df.index, fc_df[col], color=color, lw=1.2, linestyle='--')

axes[2].plot(data.index[-504:],
             (spread - spread.rolling(252).mean()) / spread.rolling(252).std(),
             color='darkorange', lw=0.7)
axes[2].axhline(2, color='r', lw=0.8, linestyle='--', label='\u00b12')
axes[2].axhline(-2, color='r', lw=0.8, linestyle='--')
axes[2].axhline(0, color='k', lw=0.5)
axes[2].set_title("Z-Score of Spread (Rolling 1-year window)")
axes[2].legend()

plt.tight_layout()
plt.savefig("vecm_yield_analysis.pdf", dpi=150)
plt.show()

