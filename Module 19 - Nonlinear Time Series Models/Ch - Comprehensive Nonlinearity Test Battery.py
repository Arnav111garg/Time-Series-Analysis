import numpy as np
import pandas as pd
import yfinance as yf
from statsmodels.tsa.stattools import acf
from statsmodels.stats.diagnostic import acorr_ljungbox
from statsmodels.regression.linear_model import OLS
from statsmodels.tools import add_constant
from scipy import stats
import warnings; warnings.filterwarnings('ignore')

# Data
spy = yf.download("SPY", start="2000-01-01", end="2024-01-01")
# Handle yfinance multi-index columns
if isinstance(spy.columns, pd.MultiIndex):
    if 'Adj Close' in spy.columns.levels[0]:
        spy = spy['Adj Close']
    else:
        spy = spy['Close']
else:
    spy = spy['Adj Close'] if 'Adj Close' in spy else spy['Close']

spy = spy.dropna()
r = 100 * np.log(spy / spy.shift(1)).dropna()

def nonlinearity_battery(y, name, p=5):
    """Run a battery of nonlinearity tests."""
    print(f"\n{'='*60}")
    print(f"Nonlinearity Test Battery: {name}")
    print('='*60)
    y_arr = y.values if hasattr(y, 'values') else np.array(y)
    T = len(y_arr)

    # 1. RESET Test
    print("\n [1] RESET Test (H0: linearity)")
    yt = y_arr[p:]
    Xmat = np.column_stack([y_arr[p - j : T - j] for j in range(1, p + 1)])
    X_c = add_constant(Xmat)
    lin_fit = OLS(yt, X_c).fit()
    y_hat = lin_fit.fittedvalues
    X_aug = np.column_stack([X_c, y_hat**2, y_hat**3])
    aug_fit = OLS(yt, X_aug).fit()

    # F-test for the augmented terms
    rss_r = np.sum(lin_fit.resid**2)
    rss_u = np.sum(aug_fit.resid**2)
    df1 = 2; df2 = T - p - 1 - 2
    F_reset = ((rss_r - rss_u) / df1) / (rss_u / df2)
    p_reset = 1 - stats.f.cdf(F_reset, df1, df2)
    print(f"F={F_reset:.4f}, p={p_reset:.4f} {' -> NONLINEAR' if p_reset < 0.05 else ' -> linear'}")

    # 2. McLeod-Li Test
    print("\n [2] McLeod-Li Test (H0: no ARCH)")
    resid = lin_fit.resid
    lb_sq = acorr_ljungbox(resid**2, lags=[5, 10, 20], return_df=True)
    for lag, pval in zip([5, 10, 20], lb_sq['lb_pvalue'].values):
        q_val = lb_sq['lb_stat'].values[[5, 10, 20].index(lag)]
        print(f"Lag {lag:2d}: Q={q_val:.3f}, p={pval:.4f} {' -> ARCH' if pval < 0.05 else ''}")

    # 3. BDS Test
    print("\n [3] BDS Test (H0: i.i.d.)")
    try:
        # Try statmodels' built-in BDS test first to avoid import and calculation errors
        from statsmodels.tsa.stattools import bds as bds_test
        bds_results = bds_test(resid, max_dim=4)
        for m, (stat, pval) in enumerate(zip(bds_results[0], bds_results[1]), start=2):
            print(f"m={m}: stat={stat:.4f}, p={pval:.4f} {' -> NONLINEAR' if pval < 0.05 else ''}")
    except Exception:
        # Manual BDS (simplified, ensuring correct matched sequence lengths)
        def corr_integral(z, eps):
            T_len = len(z)
            pairs = np.sum(np.abs(z[:, None] - z[None, :]) < eps) - T_len
            return pairs / (T_len * (T_len - 1)) if T_len > 1 else 0
        eps = resid.std()
        C1 = corr_integral(resid, eps)
        for m in range(2, 5):
            # Ensure each embedding dimension slice has identical length: T - m + 1
            embed = np.array([resid[i : T - m + 1 + i] for i in range(m)]).T
            n_embed = len(embed)
            if n_embed > 1:
                Cm = np.sum([np.all(np.abs(embed[i] - embed[j]) < eps)
                             for i in range(n_embed)
                             for j in range(i + 1, n_embed)]) * 2 / (n_embed * (n_embed - 1))
            else:
                Cm = 0
            bds_stat = (Cm - C1**m) / (eps * 0.01 + 1e-10)
            print(f"m={m}: BDS approx stat={bds_stat:.4f}")

    # 4. Keenan (1985) bilinear test
    print("\n [4] Keenan Test (H0: no bilinear structure)")
    resid_sq = resid**2
    Xfit = add_constant(y_hat.reshape(-1, 1))
    aux_fit = OLS(resid_sq, Xfit).fit()
    aux_resid = aux_fit.resid
    reg3 = OLS(aux_resid[:-1]**2, resid[1:].reshape(-1, 1)).fit()
    t_stat = reg3.params[0] / reg3.bse[0]
    p_val = 2 * (1 - stats.t.cdf(abs(t_stat), df=len(aux_resid) - 2))
    print(f"t={t_stat:.4f}, p={p_val:.4f} {' -> BILINEAR ' if p_val < 0.05 else ' -> no bilinear'}")

    # 5. Sign Bias Test
    print("\n [5] Sign Bias Test (H0: symmetric)")
    e_neg = (resid < 0).astype(float)
    e_pos = (resid > 0).astype(float)
    X_sb = add_constant(np.column_stack([
        e_neg[:-1], resid[:-1] * e_neg[:-1], resid[:-1] * e_pos[:-1]
    ]))
    y_sb = resid[1:]**2
    sb_fit = OLS(y_sb, X_sb).fit()
    F_sb = sb_fit.f_test(np.eye(3, 4, 1)).fvalue
    p_sb = sb_fit.f_test(np.eye(3, 4, 1)).pvalue
    print(f"F={float(F_sb):.4f}, p={float(p_sb):.4f} {' -> ASYMMETRIC' if float(p_sb) < 0.05 else ' -> symmetric'}")

# Run tests
nonlinearity_battery(r, "SPY Daily Log Returns")

# GARCH Residuals
try:
    from arch import arch_model
    garch_fit = arch_model(r, vol='GARCH', p=1, q=1, dist='t').fit(disp='off')
    std_resid = garch_fit.resid / garch_fit.conditional_volatility
    nonlinearity_battery(std_resid.dropna(), "GARCH(1,1)-t Standardized Residuals")
except ImportError:
    print("\n'arch' package not installed. Skipping GARCH standardized residuals test.")

