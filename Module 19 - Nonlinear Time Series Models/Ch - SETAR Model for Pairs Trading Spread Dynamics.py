def setar_loglik(threshold, y, d=1):
    """
    Log-likelihood of 2-regime SETAR(1) given threshold r.
    y : the spread series (numpy array)
    d : delay parameter
    """
    T = len(y)
    yt = y[d:]
    yt_lag = y[:-d]

    mask_lo = yt_lag <= threshold
    mask_hi = yt_lag > threshold

    ll = 0
    for mask in [mask_lo, mask_hi]:
        if mask.sum() < 5:
            return 1e10
        yt_m = yt[mask]
        yt_l_m = yt_lag[mask]
        X_m = add_constant(yt_l_m)
        try:
            reg_m = OLS(yt_m, X_m).fit()
            rss = np.sum(reg_m.resid**2)
            sig2 = rss / len(yt_m)
            ll += -0.5 * len(yt_m) * (np.log(2 * np.pi * sig2) + 1)
        except Exception:
            return 1e10
    return -ll

