# Tsay Threshold Test
def tsay_threshold_test(y, p=1, d=1):
    """
    Tsay (1989) F-test for threshold nonlinearity in AR(p) model.
    Uses arranged autoregression.
    """
    T = len(y)
    yt = y[max(p, d):]
    # Build regressors
    X = np.column_stack([y[max(p, d) - j : T - j] for j in range(1, p + 1)])

    # Sort by threshold variable (y_{t - d})
    y_thresh = y[max(p, d) - d : T - d]
    sort_idx = np.argsort(y_thresh)
    yt_s = yt[sort_idx]
    X_s = X[sort_idx]

    # Recursive residuals via expanding window
    min_obs = p + 5
    resid_rec = []
    for t in range(min_obs, len(yt_s)):
        Xt = X_s[:t]; yt_t = yt_s[:t]
        beta_t = np.linalg.lstsq(Xt, yt_t, rcond=None)[0]
        pred_t = X_s[t] @ beta_t
        resid_rec.append(yt_s[t] - pred_t)
    resid_rec = np.array(resid_rec)

    # F-test: are recursive residuals correlated with lagged threshold var?
    thresh_lag = y_thresh[sort_idx][min_obs:]
    X_test = add_constant(thresh_lag.reshape(-1, 1))
    reg_test = OLS(resid_rec, X_test).fit()
    F_stat = reg_test.fvalue
    F_p = reg_test.f_pvalue
    return F_stat, F_p

