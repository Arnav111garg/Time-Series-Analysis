# 3-State HMM with GARCH-like features via Student-t emissions
import numpy as np
import pandas as pd
import yfinance as yf
from hmmlearn import hmm
import matplotlib.pyplot as plt
from scipy.stats import t as student_t
import warnings
warnings.filterwarnings('ignore')

# Secure downloading and formatting of daily SPY data
spy_raw = yf.download("SPY", start="2000-01-01", end="2026-01-01", progress=False)
if isinstance(spy_raw.columns, pd.MultiIndex):
    spy = spy_raw['Adj Close'].iloc[:, 0] if 'Adj Close' in spy_raw.columns.levels[0] else spy_raw['Close'].iloc[:, 0]
else:
    spy = spy_raw['Adj Close'] if 'Adj Close' in spy_raw.columns else spy_raw['Close']

spy = spy.dropna()
r = 100 * np.log(spy / spy.shift(1)).dropna()
X = r.values.reshape(-1, 1)

# 3-state HMM: Bull, Bear, Crisis
N = 3
best_ll = -np.inf
best_model = None

for seed in range(30):
    model = hmm.GaussianHMM(
        n_components=N,
        covariance_type='diag',
        n_iter=1000,
        tol=1e-8,
        random_state=seed
    )
    try:
        model.fit(X)
        ll = model.score(X)
        if ll > best_ll:
            best_ll = ll
            best_model = model
    except Exception:
        pass

if best_model is None:
    raise RuntimeError("Failed to fit GaussianHMM. Verify input returns data structure.")

states = best_model.predict(X)
probs = best_model.predict_proba(X)

# Sort states by mean return: bear (-), neutral (0), bull (+)
order = np.argsort(best_model.means_.flatten())
labels = {order[0]: 'Bear/Crisis', order[1]: 'Neutral', order[2]: 'Bull'}
state_colors = {order[0]: 'crimson', order[1]: 'goldenrod', order[2]: 'steelblue'}

print("\n3-STATE HMM ANALYSIS")
print("=" * 60)
for s in range(N):
    mask = (states == s)
    state_mean = float(best_model.means_[s, 0])
    state_vol = float(np.sqrt(best_model.covars_[s, 0]))
    ann_sharpe = (state_mean * 252) / (state_vol * np.sqrt(252))
    print(f"\nState {s} [{labels.get(s, '?')}]:")
    print(f"  Daily mean: {state_mean:+.4f}%")
    print(f"  Daily vol: {state_vol:+.4f}%")
    print(f"  Ann. Sharpe: {ann_sharpe:+.2f}")
    print(f"  Freq: {mask.mean() * 100:.1f}%")
    print(f"  Avg duration: {1 / (1 - best_model.transmat_[s, s]):.1f} days")

# Regime-switching trading strategy setup
bull_state = order[2]
bear_state = order[0]
p_bull = probs[:, bull_state]
p_bear = probs[:, bear_state]

# Signal logic: long when bull_prob > 0.6, short when bear_prob > 0.6, else flat
signal = np.where(p_bull > 0.60, 1, np.where(p_bear > 0.60, -1, 0))
signal_series = pd.Series(signal, index=r.index).shift(1).fillna(0)  # shift to avoid lookahead bias

strategy_ret = signal_series * r / 100
bh_ret = r / 100

# Performance metrics evaluator
def performance(rets, name):
    rets = rets.dropna()
    ann_ret = rets.mean() * 252
    ann_vol = rets.std() * np.sqrt(252)
    sr = ann_ret / ann_vol if ann_vol > 0 else 0.0
    cum = (1 + rets).cumprod()
    max_dd = (cum / cum.cummax() - 1).min()
    calmar = ann_ret / abs(max_dd) if max_dd != 0 else 0.0

    print(f"\n{name}:")
    print(f"  Ann. Return: {ann_ret * 100:+.2f}%")
    print(f"  Ann. Volatility: {ann_vol * 100:.2f}%")
    print(f"  Sharpe: {sr:.3f}")
    print(f"  Max Drawdown: {max_dd * 100:.2f}%")
    print(f"  Calmar: {calmar:.3f}")
    return cum

print("\n=== HMM Regime Trading Strategy Performance ===")
cum_strat = performance(strategy_ret, "HMM Regime Strategy")
cum_bh = performance(bh_ret, "Buy and Hold SPY")

