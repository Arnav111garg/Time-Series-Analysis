# Full HMM implementation on equity returns
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches
import yfinance as yf
from hmmlearn import hmm
from scipy import stats
import warnings
warnings.filterwarnings('ignore')

# Secure data download
spy_raw = yf.download("SPY", start="2000-01-01", end="2024-01-01", progress=False)
if isinstance(spy_raw.columns, pd.MultiIndex):
    spy = spy_raw['Adj Close'].iloc[:, 0] if 'Adj Close' in spy_raw.columns.levels[0] else spy_raw['Close'].iloc[:, 0]
else:
    spy = spy_raw['Adj Close'] if 'Adj Close' in spy_raw.columns else spy_raw['Close']

spy = spy.dropna()
r = 100 * np.log(spy / spy.shift(1)).dropna()
X = r.values.reshape(-1, 1)

# Grid search: N=2, 3, 4, 5 regimes
print("=" * 60)
print("HMM Model Selection: Gaussian Emissions")
print("=" * 60)

hmm_fits = {}
for n_states in [2, 3, 4, 5]:
    best_ll = -np.inf
    best_model = None
    # Multiple random restarts to avoid local optima
    for seed in range(20):
        model = hmm.GaussianHMM(
            n_components=n_states,
            covariance_type='full',
            n_iter=500,
            tol=1e-6,
            random_state=seed,
            init_params='stmc',
            params='stmc'
        )
        try:
            model.fit(X)
            ll = model.score(X)
            if ll > best_ll:
                best_ll = ll
                best_model = model
        except Exception:
            pass

    if best_model is not None:
        k_params = (n_states ** 2 - n_states + n_states * 2)  # trans + means + vars
        aic = -2 * best_ll + 2 * k_params
        bic = -2 * best_ll + k_params * np.log(len(X))
        hmm_fits[n_states] = {
            'model': best_model,
            'LL': best_ll,
            'AIC': aic,
            'BIC': bic,
            'K': k_params
        }
        print(f"N={n_states} : LL={best_ll:.2f}, AIC={aic:.2f}, BIC={bic:.2f}, K={k_params}")

best_N = min(hmm_fits, key=lambda n: hmm_fits[n]['BIC'])
print(f"\nBest N by BIC: {best_N} states")

# We fit the 2-state HMM for detailed regime analysis
N = 2
model2 = hmm_fits[N]['model']
states2 = model2.predict(X)
probs2 = model2.predict_proba(X)

# Sort states so state 0 is High-Vol Bear and state 1 is Low-Vol Bull
order = np.argsort(model2.means_.flatten())
state_labels = {order[0]: 'Bear/High-Vol', order[1]: 'Bull/Low-Vol'}

# Regime statistics
print(f"\n{'=' * 60}")
print("2-STATE HMM RESULTS")
print(f"{'=' * 60}")
for s in range(N):
    mask = (states2 == s)
    regime_ret = r.values[mask]
    dur = np.mean([
        len(list(g)) for _, g in __import__('itertools').groupby(states2 == s) if _
    ])
    print(f"\nState {s} [{state_labels.get(s, '?')}]:")
    print(f"  Mean return (daily %): {model2.means_[s, 0]:+.4f}")
    print(f"  Volatility (daily %): {np.sqrt(model2.covars_[s, 0, 0]):.4f}")
    print(f"  Ann. Return: {model2.means_[s, 0] * 252:+.2f}%")
    print(f"  Ann. Volatility: {np.sqrt(model2.covars_[s, 0, 0] * 252):.2f}%")
    print(f"  Fraction of days: {mask.mean() * 100:.1f}%")
    print(f"  Persistence (p_ii): {model2.transmat_[s, s]:.4f}")
    print(f"  Expected duration: {1 / (1 - model2.transmat_[s, s]):.1f} days")

print(f"\nTransition Matrix:")
tm_df = pd.DataFrame(
    model2.transmat_,
    index=[f"From {state_labels.get(s, s)}" for s in range(N)],
    columns=[f"To {state_labels.get(s, s)}" for s in range(N)]
)
print(tm_df.to_string(float_format='{:.4f}'.format))

