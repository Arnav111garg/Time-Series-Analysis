import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from statsmodels.graphics.tsaplots import plot_acf, plot_pacf
from statsmodels.stats.diagnostic import acorr_ljungbox
from statsmodels.tsa.stattools import acf, pacf

# Data
data = yf.download("SPY", start="2010-01-01", end="2024-01-01", auto_adjust=False)["Adj Close"]
returns = np.log(data / data.shift(1)).dropna()
sq_ret = returns**2

fig, axes = plt.subplots(3, 2, figsize=(10, 8))
plot_acf(data, lags=40, ax=axes[0, 0], title="ACF: SPY Price Level", alpha=0.05)
plot_pacf(data, lags=40, ax=axes[0, 1], title="PACF: SPY Price Level", alpha=0.05, method='ywm')

# Row 2: Log returns ACF/PACF
plot_acf(returns, lags=40, ax=axes[1, 0], title="ACF: SPY Log Returns", alpha=0.05)
plot_pacf(returns, lags=40, ax=axes[1, 1], title="PACF: SPY Log Returns", alpha=0.05, method='ywm')

# Row 3: Squared returns ACF/PACF (captures ARCH effects)
plot_acf(sq_ret, lags=40, ax=axes[2, 0], title="ACF: SPY Squared Returns", alpha=0.05)
plot_pacf(sq_ret, lags=40, ax=axes[2, 1], title="PACF: SPY Squared Returns", alpha=0.05, method='ywm')

for ax in axes.flat:
    ax.axhline(0, color='black', linewidth=0.8)
    ax.set_xlabel("Lag")

plt.tight_layout()
plt.savefig("acf_pacf_analysis.pdf", dpi=150)
plt.show()

# Ljung-Box test on returns
print("\nLjung-Box Test: Log Returns")
lb_ret = acorr_ljungbox(returns, lags=[5, 10, 15, 20, 30], return_df=True)
print(lb_ret.to_string())

print("\nLjung-Box Test: Squared Log Returns (ARCH test)")
lb_sq = acorr_ljungbox(sq_ret, lags=[5, 10, 15, 20, 30], return_df=True)
print(lb_sq.to_string())

# Numerical ACF and PACF values
acf_vals = acf(returns, nlags=20, alpha=0.05)
pacf_vals = pacf(returns, nlags=20, alpha=0.05, method='ywm')

print("\nLag ACF 95% CI Lower 95% CI Upper")
for h in range(1, 21):
    ci = acf_vals[1][h]
    print(f" {h:2d} {acf_vals[0][h]:+.4f} [{ci[0]:+.4f}, {ci[1]:+.4f}]")

