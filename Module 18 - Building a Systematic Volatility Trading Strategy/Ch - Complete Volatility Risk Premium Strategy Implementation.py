import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
import pandas_datareader as pdr
from arch import arch_model
from hmmlearn import hmm
from scipy import stats
import warnings; warnings.filterwarnings('ignore')

print("Loading data...")
# In modern yfinance versions, download() returns adjusted prices in the 'Close' column by default
spy = yf.download("SPY", start="2004-01-01", end="2024-01-01", multi_level_index=False)["Close"]
vxx = yf.download("VXX", start="2009-01-30", end="2024-01-01", multi_level_index=False)["Close"]
vix = pdr.get_data_fred('VIXCLS', start='2004-01-01', end='2024-01-01').squeeze()

ret_spy = 100 * np.log(spy / spy.shift(1)).dropna()
ret_vxx = 100 * np.log(vxx / vxx.shift(1)).dropna()

# Align using the indexes of the returns directly to avoid dropped-row mismatch
common_idx = ret_spy.index.intersection(ret_vxx.index).intersection(vix.index)
ret_spy = ret_spy.loc[common_idx]
ret_vxx = ret_vxx.loc[common_idx]
vix_aligned = vix.loc[common_idx]

#
# MODULE 1: GARCH VOLATILITY FORECASTING
#
print("Fitting rolling GARCH models...")

window = 252 # 1-year rolling estimation
garch_vol_forecasts = pd.Series(np.nan, index=ret_spy.index)

for t in range(window, len(ret_spy)):
    if t % 100 == 0:
        print(f"Progress: {t}/{len(ret_spy)} ({t / len(ret_spy) * 100:.0f}%)")
    train = ret_spy.iloc[t - window : t]
    try:
        fit = arch_model(train, vol='GARCH', p=1, q=1, dist='t', rescale=False).fit(disp='off', options={'maxiter': 300})
        # 1-day ahead conditional vol, annualized
        fc = fit.forecast(horizon=1, reindex=False)
        garch_vol_forecasts.iloc[t] = np.sqrt(fc.variance.values[-1, 0] * 252)
    except Exception:
        pass

garch_vol_forecasts = garch_vol_forecasts.dropna()

#
# MODULE 2: VOLATILITY RISK PREMIUM
#
# VRP = Implied Vol (VIX) - Expected Realized Vol (GARCH)
vrp = pd.Series(index=garch_vol_forecasts.index, dtype=float)
for idx in garch_vol_forecasts.index:
    if idx in vix_aligned.index:
        vrp[idx] = vix_aligned[idx] - garch_vol_forecasts[idx]

vrp = vrp.dropna()

# Rolling z-score of VRP (for signal generation)
vrp_zscore = (vrp - vrp.rolling(63).mean()) / (vrp.rolling(63).std() + 1e-10)
vrp_zscore = vrp_zscore.dropna()

print(f"\nVRP Statistics:")
print(f"Mean VRP (VIX-GARCH): {vrp.mean():.2f}%")
print(f"Std VRP: {vrp.std():.2f}%")
print(f"% of days VRP > 0: {(vrp > 0).mean() * 100:.1f}%")
print(f"% of days VRP > 5%: {(vrp > 5).mean() * 100:.1f}%")

#
# MODULE 3: HMM REGIME DETECTION
#
print("\nFitting HMM for regime detection...")

# Use VIX changes + VRP for HMM features
hmm_features = pd.concat([
    vix_aligned.diff(), # VIX daily change
    vrp, # VRP level
    ret_spy.rolling(5).std() * np.sqrt(252), # 5d realized vol
], axis=1).dropna()
hmm_features.columns = ['dvix', 'vrp', 'rv5d']

# Normalize features
hmm_feat_norm = ((hmm_features - hmm_features.expanding().mean()) / (hmm_features.expanding().std() + 1e-10)).dropna()
Z_hmm = hmm_feat_norm.values

# Fit 3-state HMM
best_ll, best_hmm = -np.inf, None
for seed in range(20):
    m = hmm.GaussianHMM(n_components=3, covariance_type='full', n_iter=200, random_state=seed)
    try:
        m.fit(Z_hmm)
        ll = m.score(Z_hmm)
        if ll > best_ll:
            best_ll, best_hmm = ll, m
    except Exception:
        pass

hmm_states = best_hmm.predict(Z_hmm)
hmm_probs = best_hmm.predict_proba(Z_hmm)

# Sort states by VRP level (state 0 = low VRP, state 2 = high VRP)
state_vrp_means = [hmm_features['vrp'].values[hmm_features.index.isin(hmm_feat_norm.index[hmm_states == k])].mean() for k in range(3)]
order = np.argsort(state_vrp_means) # ascending VRP
state_map = {order[0]: 'Low-VRP / Crisis', order[1]: 'Normal', order[2]: 'High-VRP / Sell-Vol'}
print("HMM States (sorted by VRP):")
for k, lab in state_map.items():
    mask = hmm_states == k
    print(f"State {k} [{lab}]: VRP={state_vrp_means[k]:.2f}%, freq={mask.mean() * 100:.1f}%, dur={1/(1-best_hmm.transmat_[k, k]):.0f}d")

#
# MODULE 4: TRADING SIGNAL AND BACKTEST
#
print("\nGenerating trading signals...")

# High-VRP state index
high_vrp_state = order[2]

# Align all signals to common index
common2 = vrp_zscore.index.intersection(hmm_feat_norm.index).intersection(ret_vxx.index)
vrp_z_aligned = vrp_zscore.loc[common2]
hmm_p_highvrp = pd.Series(hmm_probs[:, high_vrp_state], index=hmm_feat_norm.index).loc[common2]
ret_vxx_aligned = ret_vxx.loc[common2]
ret_spy_aligned = ret_spy.loc[common2]

# Signal construction
vrp_signal = (vrp_z_aligned > 0.5).astype(float)
hmm_signal = (hmm_p_highvrp > 0.50).astype(float)

# Combined signal: both must agree
combined = (vrp_signal * hmm_signal).shift(1).fillna(0) # shift 1 to avoid lookahead

# Position sizing
pos_size = combined * np.minimum(1.0, vrp_z_aligned.shift(1).fillna(0).clip(lower=0) / 2)

# P&L calculation
pnl_vxx = -pos_size * ret_vxx_aligned / 100 # short VXX
pnl_spy = pos_size * 0.20 * ret_spy_aligned / 100 # 20% SPY hedge
pnl_total = pnl_vxx + pnl_spy
bh_spy = ret_spy_aligned / 100

# Transaction costs
tc_per_trade = 0.0010 # 10 bps per side
position_change = (pos_size.diff() != 0).astype(float)
tc = position_change * tc_per_trade
pnl_net = pnl_total - tc

#
# MODULE 5: PERFORMANCE ANALYSIS
#
def full_performance(rets, name, benchmark=None):
    rets = rets.dropna()
    cum = (1 + rets).cumprod()
    ann_ret = rets.mean() * 252
    ann_vol = rets.std() * np.sqrt(252)
    sharpe = ann_ret / ann_vol if ann_vol > 0 else 0
    max_dd = (cum / cum.cummax() - 1).min()
    calmar = ann_ret / abs(max_dd) if max_dd != 0 else np.nan
    skew_ = stats.skew(rets)
    kurt_ = stats.kurtosis(rets)
    var99 = np.percentile(rets, 1)
    n_pos = (rets > 0).mean()

    print(f"\n{' '*50}")
    print(f" {name}")
    print(f"{' '*50}")
    print(f" Ann. Return: {ann_ret * 100:+.2f}%")
    print(f" Ann. Volatility: {ann_vol * 100:.2f}%")
    print(f" Sharpe Ratio: {sharpe:.3f}")
    print(f" Max Drawdown: {max_dd * 100:.2f}%")
    print(f" Calmar Ratio: {calmar:.3f}")
    print(f" Skewness: {skew_:.3f}")
    print(f" Excess Kurtosis: {kurt_:.3f}")
    print(f" Daily 99% VaR: {var99 * 100:.2f}%")
    print(f" Win Rate: {n_pos * 100:.1f}%")
    if benchmark is not None:
        beta = np.cov(rets.values, benchmark.reindex(rets.index).fillna(0).values)[0, 1] / \
               np.var(benchmark.reindex(rets.index).fillna(0).values)
        alpha_ann = ann_ret - beta * benchmark.reindex(rets.index).fillna(0).mean() * 252
        print(f" Beta (vs SPY): {beta:.3f}")
        print(f" Alpha (ann.): {alpha_ann * 100:+.2f}%")
    return cum

print("\n" + "="*50)
print("VOLATILITY RISK PREMIUM STRATEGY PERFORMANCE")
print("="*50)
cum_strat = full_performance(pnl_net, "VRP Strategy (net of TC)", benchmark=bh_spy)
cum_bh = full_performance(bh_spy, "SPY Buy and Hold")

# VISUALIZATION
fig = plt.figure(figsize=(16, 18))
gs = fig.add_gridspec(5, 2, hspace=0.45, wspace=0.3)

# 1. VRP over time
ax1 = fig.add_subplot(gs[0, :])
ax1.plot(vrp.index, vrp.values, 'navy', lw=0.7, alpha=0.7)
ax1.axhline(vrp.mean(), color='r', lw=1.5, linestyle='--', label=f'Mean: {vrp.mean():.2f}%')
ax1.fill_between(vrp.index, vrp, vrp.mean(), where=(vrp > vrp.mean()), color='green', alpha=0.2, label='VRP above mean (sell vol)')
ax1.fill_between(vrp.index, vrp, vrp.mean(), where=(vrp < vrp.mean()), color='red', alpha=0.2, label='VRP below mean (flat/hedge)')
ax1.set_title("Volatility Risk Premium: VIX GARCH Forecast", fontweight='bold')
ax1.set_ylabel("VRP (%)")
ax1.legend(fontsize=9)

# 2. HMM state probabilities
ax2 = fig.add_subplot(gs[1, :])
colors_hmm = ['#FF4444', '#FFB300', '#4CAF50']
ax2.stackplot(hmm_feat_norm.index,
              hmm_probs[:, order[0]], hmm_probs[:, order[1]], hmm_probs[:, order[2]],
              labels=[state_map[order[0]], state_map[order[1]], state_map[order[2]]],
              colors=colors_hmm, alpha=0.8)
ax2.set_title("HMM Regime Posterior Probabilities", fontweight='bold')
ax2.set_ylabel("Probability")
ax2.legend(loc='upper right', fontsize=9)

# 3. Position sizing
ax3 = fig.add_subplot(gs[2, :])
ax3.fill_between(pos_size.index, 0, pos_size.values, where=(pos_size.values > 0), color='green', alpha=0.7, label='Short VXX (sell vol)')
ax3.fill_between(pos_size.index, 0, pos_size.values, where=(pos_size.values < 0), color='red', alpha=0.7, label='Long VXX (hedge)')
ax3.set_title("Position Sizing (0 = flat, 1 = full short VXX)", fontweight='bold')
ax3.set_ylabel("Position Size")
ax3.legend()

# 4. Cumulative returns
ax4 = fig.add_subplot(gs[3, :])
ax4.plot(cum_strat.index, cum_strat.values, 'darkgreen', lw=2, label=f'VRP Strategy (Sharpe={pnl_net.mean() * 252 / (pnl_net.std() * np.sqrt(252)):.2f})')
ax4.plot(cum_bh.index, cum_bh.values, 'navy', lw=1.5, linestyle='--', label=f'SPY B&H (Sharpe={bh_spy.mean() * 252 / (bh_spy.std() * np.sqrt(252)):.2f})')
ax4.set_yscale('log')
ax4.set_title("Cumulative Wealth (Log Scale)", fontweight='bold')
ax4.set_ylabel("Wealth ($1 initial)")
ax4.legend()

# 5a. Monthly returns heatmap
ax5a = fig.add_subplot(gs[4, 0])
monthly_ret = pnl_net.resample('M').apply(lambda x: (1+x).prod() - 1)
monthly_df = pd.DataFrame({'ret': monthly_ret})
monthly_df['year'] = monthly_df.index.year
monthly_df['month'] = monthly_df.index.month
pivot = monthly_df.pivot(index='year', columns='month', values='ret')
pivot.columns = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
import matplotlib.colors as mcolors
cmap = mcolors.LinearSegmentedColormap.from_list("rg", ["#d32f2f", "white", "#388e3c"])
im = ax5a.imshow(pivot.values, aspect='auto', cmap=cmap, vmin=-0.10, vmax=0.10)
ax5a.set_xticks(range(12)); ax5a.set_xticklabels(pivot.columns, rotation=45, fontsize=7)
ax5a.set_yticks(range(len(pivot))); ax5a.set_yticklabels(pivot.index, fontsize=7)
for i in range(pivot.shape[0]):
    for j in range(pivot.shape[1]):
        v = pivot.values[i, j]
        if not np.isnan(v):
            ax5a.text(j, i, f'{v * 100:.1f}', ha='center', va='center', fontsize=5.5, color='white' if abs(v) > 0.06 else 'black')
ax5a.set_title("Monthly Returns Heatmap", fontweight='bold', fontsize=10)
plt.colorbar(im, ax=ax5a, shrink=0.8)

# 5b. Drawdown analysis
ax5b = fig.add_subplot(gs[4, 1])
dd_strat = (cum_strat / cum_strat.cummax() - 1)
dd_bh = (cum_bh / cum_bh.cummax() - 1)
ax5b.fill_between(dd_strat.index, dd_strat.values, 0, color='darkgreen', alpha=0.5, label='VRP Strategy')
