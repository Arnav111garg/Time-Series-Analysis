# Time-varying beta estimation with the Kalman Filter
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from filterpy.kalman import KalmanFilter
from scipy.optimize import minimize
import warnings
warnings.filterwarnings('ignore')

def get_yf_series(ticker, start, end):
    # Download single ticker raw data
    df_raw = yf.download(ticker, start=start, end=end, progress=False)

    # Flatten MultiIndex columns if present (e.g. ('Adj Close', 'SPY') -> 'Adj Close')
    if isinstance(df_raw.columns, pd.MultiIndex):
        cols = [c[0] for c in df_raw.columns]
        df_flat = df_raw.copy()
        df_flat.columns = cols
    else:
        df_flat = df_raw

    # Extract key series (fallback to Close if Adj Close is missing)
    for col in ['Adj Close', 'Close']:
        if col in df_flat.columns:
            series = df_flat[col]
            # Handle potential duplicate column names after flattening
            if isinstance(series, pd.DataFrame):
                return series.iloc[:, 0].dropna()
            return series.dropna()

    raise KeyError(f"Could not find Close or Adj Close for {ticker}")

# Download and align all required data series
start_date = '2015-01-01'
end_date = '2024-01-01'
tickers = ['AAPL', 'MSFT', 'NVDA', 'JPM', 'XOM', '^GSPC']

raw_series = {}
for t in tickers:
    raw_series[t] = get_yf_series(t, start=start_date, end=end_date)

data_df = pd.DataFrame(raw_series).dropna()
returns = np.log(data_df / data_df.shift(1)).dropna()
mkt = returns['^GSPC']

def kalman_tv_beta(stock_ret, mkt_ret, Q=1e-5, R=None, alpha_init=None):
    """
    Estimate time-varying beta via Kalman filter.
    State: [alpha, beta], Obs: r_stock = alpha + beta * r_mkt + eps
    """
    T = len(stock_ret)
    if R is None:
        R = np.var(stock_ret.values) * 0.5

    n_state = 2
    kf = KalmanFilter(dim_x=n_state, dim_z=1)

    if alpha_init is None:
        from numpy.linalg import lstsq
        X0 = np.column_stack([np.ones(min(50, T)), mkt_ret.values[:min(50, T)]])
        alpha_init, beta_init = lstsq(X0, stock_ret.values[:min(50, T)], rcond=None)[0]
    else:
        beta_init = 1.0

    kf.x = np.array([[alpha_init], [beta_init]])
    kf.P = np.eye(n_state) * 1.0
    kf.Q = np.eye(n_state) * Q
    kf.R = np.array([[R]])
    kf.F = np.eye(n_state)

    betas = np.zeros(T)
    alphas = np.zeros(T)
    P_betas = np.zeros(T)

    for t in range(T):
        kf.H = np.array([[1.0, mkt_ret.values[t]]])
        kf.predict()
        kf.update(np.array([[stock_ret.values[t]]]))

        alphas[t] = kf.x[0, 0]
        betas[t] = kf.x[1, 0]
        P_betas[t] = kf.P[1, 1]

    return alphas, betas, P_betas

# Optimize Q for each stock by maximizing log-likelihood
def neg_loglik_tv_beta(log_Q, stock_ret, mkt_ret):
    Q = np.exp(log_Q)
    try:
        T = len(stock_ret)
        n_state = 2
        kf = KalmanFilter(dim_x=n_state, dim_z=1)
        X0 = np.column_stack([np.ones(min(60, T)), mkt_ret.values[:min(60, T)]])
        ab = np.linalg.lstsq(X0, stock_ret.values[:min(60, T)], rcond=None)[0]
        kf.x = np.array([[ab[0]], [ab[1]]])
        kf.P = np.eye(2)
        kf.Q = np.eye(2) * Q
        R = np.var(stock_ret.values)
        kf.R = np.array([[R]])
        kf.F = np.eye(2)

        ll = 0
        for t in range(T):
            kf.H = np.array([[1.0, mkt_ret.values[t]]])
            kf.predict()
            innov = stock_ret.values[t] - kf.H @ kf.x
            S = kf.H @ kf.P @ kf.H.T + kf.R
            ll += -0.5 * (np.log(2 * np.pi * S[0, 0]) + (innov[0] ** 2) / S[0, 0])
            kf.update(np.array([[stock_ret.values[t]]]))
        return -ll
    except Exception:
        return 1e10

stocks = ['AAPL', 'MSFT', 'NVDA', 'JPM', 'XOM']
fig, axes = plt.subplots(len(stocks), 1, figsize=(12, 8 * len(stocks)), sharex=True)
fig.suptitle("Time-Varying Beta: Kalman Filter Estimates", fontsize=14, fontweight='bold')

results_summary = {}
for i, stock in enumerate(stocks):
    opt = minimize(neg_loglik_tv_beta, x0=[-10.0],
                   args=(returns[stock], mkt),
                   method='Nelder-Mead',
                   options={'xatol': 1e-4, 'fatol': 1e-4, 'maxiter': 500})
    Q_opt = np.exp(opt.x[0])

    alphas, betas, P_betas = kalman_tv_beta(returns[stock], mkt, Q=Q_opt)
    ci_upper = betas + 1.96 * np.sqrt(P_betas)
    ci_lower = betas - 1.96 * np.sqrt(P_betas)

    ols_beta = np.cov(returns[stock], mkt)[0, 1] / np.var(mkt)
    idx = returns.index

    axes[i].plot(idx, betas, color='navy', lw=1.2, label=f'KF Beta (Q={Q_opt:.1e})')
    axes[i].fill_between(idx, ci_lower, ci_upper, alpha=0.25, color='blue', label='95% CI')
    axes[i].axhline(ols_beta, color='red', lw=1, linestyle='--', label=f'OLS Beta={ols_beta:.2f}')
    axes[i].axhline(1.0, color='gray', lw=0.8, linestyle=':')
    axes[i].set_title(f"{stock}", fontsize=11)
    axes[i].set_ylabel("Beta")
    axes[i].legend(fontsize=8)
    axes[i].set_ylim(max(-0.5, betas.min() - 0.3), min(3.5, betas.max() + 0.3))

    results_summary[stock] = {
        'OLS_beta': ols_beta,
        'KF_beta_mean': betas.mean(),
        'KF_beta_std': betas.std(),
        'Q_opt': Q_opt
    }

plt.tight_layout()
plt.savefig("kalman_tv_beta.pdf", dpi=150)
plt.show()

print("\nTime-Varying Beta Summary:")
print(pd.DataFrame(results_summary).T.to_string(float_format='{:.4f}'.format))

# Kalman Filter pairs trading with dynamic hedge ratio
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from filterpy.kalman import KalmanFilter

def kalman_pairs(Y1, Y2, delta=1e-4, Ve=0.001):
    """
    Kalman filter for time-varying pairs trading.
    State: [alpha_t, beta_t] where spread = Y1 - alpha - beta * Y2
    delta: process noise parameter (higher = faster adaptation)
    Ve: observation noise variance
    """
    T = len(Y1)
    n = 2

    # Process noise covariance (allows beta to change over time)
    Vw = delta / (1 - delta) * np.eye(n)

    # Initialize
    beta_filter = np.zeros((T, n))  # [alpha, beta]
    P = np.zeros((T, n, n))
    spread = np.zeros(T)

    # Initial state from first 20 observations
    from numpy.linalg import lstsq
    if T > 20:
        X0 = np.column_stack([np.ones(20), Y2.values[:20]])
        ab0 = lstsq(X0, Y1.values[:20], rcond=None)[0]
    else:
        ab0 = np.array([0.0, 1.0])

    beta_filter[0] = ab0
    P[0] = np.eye(n)

    R = np.array([[Ve]])
    F = np.eye(n)  # state transition: random walk

    for t in range(1, T):
        # Observation matrix: H = [1, Y2[t]]
        H = np.array([[1.0, Y2.values[t]]])
        alpha_pred = F @ beta_filter[t - 1]
        P_pred = F @ P[t - 1] @ F.T + Vw

        # Innovation
        y_pred = H @ alpha_pred
        innov = Y1.values[t] - y_pred[0]
        S = H @ P_pred @ H.T + R

        # Kalman gain
        K = P_pred @ H.T / S[0, 0]

        # Update
        beta_filter[t] = alpha_pred + K.flatten() * innov
        P[t] = (np.eye(n) - K @ H) @ P_pred

        spread[t] = innov

    df_out = pd.DataFrame({
        'alpha': beta_filter[:, 0],
        'beta': beta_filter[:, 1],
        'spread': spread
    }, index=Y1.index)

    return df_out

# Helper function to get clean yfinance series without MultiIndex or label issues
def get_yf_clean(ticker, start, end):
    df_raw = yf.download(ticker, start=start, end=end, progress=False)
    if isinstance(df_raw.columns, pd.MultiIndex):
        cols = [c[0] for c in df_raw.columns]
        df_raw.columns = cols
    for col in ['Adj Close', 'Close']:
        if col in df_raw.columns:
            series = df_raw[col]
            if isinstance(series, pd.DataFrame):
                return series.iloc[:, 0].dropna()
            return series.dropna()
    raise KeyError(f"Could not download close data for {ticker}")

# Apply to GLD-GDX pair
gld = get_yf_clean("GLD", start="2010-01-01", end="2024-01-01")
