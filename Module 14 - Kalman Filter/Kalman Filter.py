# Align
data_pair = pd.concat([gld, gdx], axis=1).dropna()
data_pair.columns = ['GLD', 'GDX']
data_pair = np.log(data_pair)  # work in log prices

kf_df = kalman_pairs(data_pair['GLD'], data_pair['GDX'], delta=1e-3, Ve=5e-4)

# Compute z-score for trading
window = 30
