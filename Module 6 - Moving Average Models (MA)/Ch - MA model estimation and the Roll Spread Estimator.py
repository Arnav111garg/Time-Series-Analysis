import numpy as np
import pandas as pd
from statsmodels.tsa.statespace.sarimax import SARIMAX

# Simulate MA(2)
np.random.seed(12)
T = 1000
theta1, theta2, sigma = 0.6, -0.3, 1.0
eps = np.random.normal(0, sigma, T)
X = np.zeros(T)
for t in range(2, T):
    X[t] = eps[t] + theta1 * eps[t - 1] + theta2 * eps[t - 2]

ma2 = SARIMAX(X, order=(0, 0, 2)).fit(disp=False)
print(ma2.summary())

# Roll (1984) Spread Estimator
def roll_spread(price_series):
    delta_p = price_series.diff().dropna()
    cov = np.cov(delta_p[1:], delta_p[:-1])[0, 1]
    if cov < 0:
        spread = 2 * np.sqrt(-cov)
    else:
        # Modified: take 0 if covariance is positive
        spread = 0.0
        print("Warning: Cov >= 0, spread set to 0")
    return spread

import yfinance as yf
# Use tick-level data proxy (daily OHLC, compute spread from High-Low)
amzn = yf.download("AMZN", start="2023-01-01", end="2024-01-01")
# Accessing the 'Close' column from the DataFrame
close_prices = amzn["Close"].squeeze()
spread_est = roll_spread(close_prices)
print(f"\nRoll spread estimate: ${spread_est:.4f}")
print(f"As fraction of price: {spread_est / close_prices.mean():.6f}")

