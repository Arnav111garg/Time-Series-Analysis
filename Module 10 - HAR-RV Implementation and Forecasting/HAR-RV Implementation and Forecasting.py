import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from statsmodels.regression.linear_model import OLS
from statsmodels.tools import add_constant
from sklearn.metrics import mean_squared_error, mean_absolute_error
import yfinance as yf

# Download SPY data
spy_df = yf.download("SPY", start="2003-01-01", end="2024-01-01", interval="1d", auto_adjust=False)
spy = spy_df["Adj Close"].squeeze()
r = np.log(spy / spy.shift(1)).dropna()

# Proxy RV: annualized daily RV proxy
rv = (r**2 * 252).rename("RV")

# Construct HAR components
df = pd.DataFrame({'RV': rv})
df['RV_d'] = df['RV']  # daily
df['RV_w'] = df['RV'].rolling(5).mean()  # weekly (5-day) avg
df['RV_m'] = df['RV'].rolling(22).mean()  # monthly (22-day) avg
df['RV_next'] = df['RV'].shift(-1)  # next-day RV (target)
df = df.dropna()

# Train/Test split
split = int(0.8 * len(df))
train, test = df.iloc[:split], df.iloc[split:]

# Fit HAR-RV
X_train = add_constant(train[['RV_d', 'RV_w', 'RV_m']])
y_train = train['RV_next']
har_fit = OLS(y_train, X_train).fit(cov_type='HAC', cov_kwds={'maxlags': 10})
print(har_fit.summary())

# Alternative: HAR-RV-J (with jump component)
# Bipower variation (BV) placeholder
df['BV'] = df['RV'] * 0.8
df['J'] = (df['RV'] - df['BV']).clip(lower=0)  # jump component

X_train_j = add_constant(train.reindex(df.index[:split])[['RV_d', 'RV_w', 'RV_m']].join(df[['J']].iloc[:split]))
har_j_fit = OLS(y_train.values, add_constant(df[['RV_d', 'RV_w', 'RV_m', 'J']].iloc[:split])).fit(cov_type='HAC', cov_kwds={'maxlags': 10})
print("\nHAR-RV-J Model:")
print(har_j_fit.params)

# Forecast evaluation
X_test = add_constant(test[['RV_d', 'RV_w', 'RV_m']])
y_test = test['RV_next']
fc_har = har_fit.predict(X_test)

# Compare vs. AR(1) on RV
X_ar1 = add_constant(train[['RV_d']])
ar1_fit = OLS(y_train, X_ar1).fit()
fc_ar1 = ar1_fit.predict(add_constant(test[['RV_d']]))

# Compare vs. 22-day rolling average (naive)
fc_naive = test['RV_m'].values

results = {
    'HAR-RV': {
        'RMSE': np.sqrt(mean_squared_error(y_test, fc_har)),
        'MAE': mean_absolute_error(y_test, fc_har)
    },
    'AR(1)-RV': {
        'RMSE': np.sqrt(mean_squared_error(y_test, fc_ar1)),
        'MAE': mean_absolute_error(y_test, fc_ar1)
    },
    'Naive-22d': {
        'RMSE': np.sqrt(mean_squared_error(y_test, fc_naive)),
        'MAE': mean_absolute_error(y_test, fc_naive)
    }
}

print("\nForecast Evaluation:")
for m, v in results.items():
    print(f"{m:<15}: RMSE={v['RMSE']:.6f}, MAE={v['MAE']:.6f}")

# Plot forecasts vs actuals
fig, axes = plt.subplots(2, 1, figsize=(14, 8), sharex=True)
axes[0].plot(y_test.index, np.sqrt(y_test), 'k-', lw=0.8, alpha=0.7, label='Actual Vol')
axes[0].plot(y_test.index, np.sqrt(fc_har), 'r--', lw=1.2, label='HAR-RV Forecast')
axes[0].plot(y_test.index, np.sqrt(fc_ar1), 'b:', lw=1.2, label='AR(1) Forecast')
axes[0].set_ylabel('Volatility (%/year)')
axes[0].set_title('HAR-RV Out-of-Sample Volatility Forecasts')
axes[0].legend()

# Scatter: actual vs predicted
axes[1].scatter(np.sqrt(y_test), np.sqrt(fc_har), s=5, alpha=0.4, color='firebrick', label='HAR-RV')
axes[1].scatter(np.sqrt(y_test), np.sqrt(fc_ar1), s=5, alpha=0.4, color='steelblue', label='AR(1)')
lims = [0, np.sqrt(y_test).max()]
axes[1].plot(lims, lims, 'k-', lw=0.8)
axes[1].set_xlabel('Actual Vol')
axes[1].set_ylabel('Forecast Vol')
axes[1].set_title('Actual vs. Predicted Volatility')
axes[1].legend()

plt.tight_layout()
plt.savefig("har_rv_forecast.pdf", dpi=150)
plt.show()

