# RISK METRICS CALCULATOR
#

class RiskMetrics:
    """
    Comprehensive risk metrics calculation engine.
    Supports multiple VaR methods and full backtesting suite.
    """
    def __init__(self, returns, weights=None):
        """
        returns: DataFrame or Series of daily log returns (as fractions)
        weights: portfolio weights (if DataFrame of returns)
        """
        if isinstance(returns, pd.DataFrame):
            self.asset_returns = returns
            if weights is None:
                weights = np.ones(returns.shape[1]) / returns.shape[1]
            self.weights = np.array(weights)
            self.returns = (returns * self.weights).sum(axis=1)
        else:
            self.returns = returns
            self.weights = None
        self.T = len(self.returns)

    #
    # VaR Methods
    #

    def historical_var(self, alpha=0.01, window=252):
        """ Historical simulation VaR (rolling window). """
        r = self.returns
        var_ts = pd.Series(np.nan, index=r.index)
        es_ts = pd.Series(np.nan, index=r.index)
        for t in range(window, self.T):
            hist = r.iloc[t - window:t].values
            var_t = -np.percentile(hist, alpha * 100)
            es_t = -hist[hist <= -var_t].mean()
            var_ts.iloc[t] = var_t
            es_ts.iloc[t] = es_t
        return var_ts.dropna(), es_ts.dropna()

    def parametric_var(self, alpha=0.01):
        """Normal (parametric) VaR. """
        mu = self.returns.mean()
        sigma = self.returns.std()
        var = -(mu + norm.ppf(alpha) * sigma)
        es = -(mu + sigma * norm.pdf(norm.ppf(alpha)) / alpha)
        return float(var), float(es)

    def garch_var(self, alpha=0.01, dist='t', window=500):
        """
        GARCH-based conditional VaR.
        Fits GARCH(1,1) on rolling window, computes 1-step ahead VaR.
        """
        r = self.returns
        var_ts = pd.Series(np.nan, index=r.index)
        es_ts = pd.Series(np.nan, index=r.index)

        print(f"Computing GARCH-{dist} VaR ({self.T} days)...")
        for t in range(window, self.T, 5): # refit every 5 days for speed
            train = r.iloc[t - window:t]
            try:
                mdl = arch_model(train * 100, vol='GARCH', p=1, q=1, dist=dist)
                fit = mdl.fit(disp='off', options={'maxiter': 300})
                fc = fit.forecast(horizon=1, reindex=False)
                sigma_t = np.sqrt(fc.variance.values[-1, 0]) / 100 # back to fraction
                mu_t = fit.params.get('mu', 0) / 100

                if dist == 't':
                    nu = fit.params.get('nu', 8)
                    # Scale t-distribution for GARCH
                    z_alpha = stats.t.ppf(alpha, df=nu)
                    var_t = -(mu_t + z_alpha * sigma_t)
                    # ES for t-distribution
                    es_t = -(mu_t - sigma_t * stats.t.pdf(z_alpha, nu) /
                             (alpha * (1 - 2/nu)) if nu > 2 else var_t * 1.2)
                else:
                    var_t = -(mu_t + norm.ppf(alpha) * sigma_t)
                    es_t = -(mu_t + sigma_t * norm.pdf(norm.ppf(alpha)) / alpha)

                # Fill for next 5 days
                for k in range(min(5, self.T - t)):
                    var_ts.iloc[t+k] = var_t
                    es_ts.iloc[t+k] = es_t
            except Exception:
                pass

        return var_ts.dropna(), es_ts.dropna()

    def filtered_historical_simulation(self, alpha=0.01, window=500):
        """
        Filtered Historical Simulation (Barone-Adesi & Giannopoulos, 1999).
        """
        r = self.returns
        var_ts = pd.Series(np.nan, index=r.index)
        es_ts = pd.Series(np.nan, index=r.index)

        print("Computing FHS VaR...")
        for t in range(window, self.T, 5):
            train = r.iloc[t - window:t]
            try:
                fit = arch_model(train * 100, vol='GARCH', p=1, q=1, dist='normal').fit(disp='off', options={'maxiter': 200})
                # Standardized residuals from the window
                std_resid = (fit.resid / fit.conditional_volatility).dropna().values
                # 1-step ahead conditional vol
                fc_var = fit.forecast(horizon=1, reindex=False).variance.values[-1, 0]
                sigma_t = np.sqrt(fc_var) / 100

                # Simulate by resampling std residuals
                sim_rets = std_resid * sigma_t # rescale to current vol

                var_t = -np.percentile(sim_rets, alpha * 100)
                es_t = -sim_rets[sim_rets <= -var_t].mean()

                for k in range(min(5, self.T - t)):
                    var_ts.iloc[t+k] = var_t
                    es_ts.iloc[t+k] = es_t
            except Exception:
                pass

        return var_ts.dropna(), es_ts.dropna()

    #
    # Backtesting
    #
    def backtest_var(self, var_series, alpha=0.01, name="VaR Method"):
        """
        Backtest a VaR series against realized returns.
        Computes Kupiec and Christoffersen tests.
        """
        # Align
        common = self.returns.index.intersection(var_series.index)
        r_bt = self.returns.loc[common]
        var_bt = var_series.loc[common]

        # Violations: loss exceeds VaR
        violations = (-r_bt > var_bt).astype(int)
        T_bt = len(violations)
        T1 = violations.sum() # number of violations
        T0 = T_bt - T1
        viol_rate = T1 / T_bt

        # Kupiec test (unconditional coverage)
        if 0 < T1 < T_bt:
            LR_uc = -2 * (T1 * np.log(alpha) + T0 * np.log(1 - alpha)) + \
                    2 * (T1 * np.log(T1/T_bt) + T0 * np.log(T0/T_bt) if T1 > 0 and T0 > 0 else 0)
            p_uc = 1 - chi2.cdf(LR_uc, df=1)
        else:
            LR_uc, p_uc = 0, 1

        # Christoffersen conditional coverage
        viol_arr = violations.values
        n00 = np.sum((viol_arr[:-1] == 0) & (viol_arr[1:] == 0))
        n01 = np.sum((viol_arr[:-1] == 0) & (viol_arr[1:] == 1))
        n10 = np.sum((viol_arr[:-1] == 1) & (viol_arr[1:] == 0))
        n11 = np.sum((viol_arr[:-1] == 1) & (viol_arr[1:] == 1))

        pi0 = n01 / (n00 + n01) if (n00 + n01) > 0 else 0.5
        pi1 = n11 / (n10 + n11) if (n10 + n11) > 0 else 0.5
        pi = (n01 + n11) / (n00 + n01 + n10 + n11) if T_bt > 1 else 0.5

        if 0 < pi < 1 and 0 < pi0 < 1 and 0 < pi1 < 1:
            LR_ind = -2 * ((n00 + n10) * np.log(1 - pi) + (n01 + n11) * np.log(pi)) + \
                     2 * (n00 * np.log(1 - pi0) + n01 * np.log(pi0) + n10 * np.log(1 - pi1) + n11 * np.log(pi1) if all(x > 0 for x in [n00, n01, n10, n11]) else 0)
            p_ind = 1 - chi2.cdf(LR_ind, df=1)
            LR_cc = LR_uc + LR_ind
            p_cc = 1 - chi2.cdf(LR_cc, df=2)
        else:
            LR_ind, p_ind = 0, 1
            LR_cc, p_cc = LR_uc, p_uc

        # Basel traffic light
        violations_250 = violations[-250:].sum() if T_bt >= 250 else T1
        if violations_250 <= 4:
            traffic = 'GREEN'
        elif violations_250 <= 9:
            traffic = 'YELLOW'
        else:
            traffic = 'RED'

        result = {
            'Method': name,
            'T': T_bt,
            'Violations': int(T1),
            'Viol_Rate': viol_rate,
            'Expected': alpha,
            'LR_uc': LR_uc,
            'p_uc': p_uc,
            'Pass_uc': p_uc > 0.05,
            'LR_cc': LR_cc,
            'p_cc': p_cc,
            'Pass_cc': p_cc > 0.05,
            'Basel': traffic,
            'Viol_250d': int(violations_250)
        }
        return result, violations, r_bt, var_bt

    def component_var(self, alpha=0.01):
        """
        Component VaR for a multi-asset portfolio.
        """
        if self.weights is None or not hasattr(self, 'asset_returns'):
            print("Component VaR requires portfolio with multiple assets.")
            return None

        # Covariance matrix
        Sigma = self.asset_returns.cov().values
        w = self.weights
        port_vol = np.sqrt(w @ Sigma @ w)

        # Marginal contribution to portfolio variance
        mcv = Sigma @ w / port_vol

        # Marginal VaR
        z_alpha = norm.ppf(alpha)
        marg_var = z_alpha * mcv

        # Component VaR
        comp_var = w * marg_var
        total_var = z_alpha * port_vol
        comp_var_pct = comp_var / total_var

        return pd.DataFrame({
            'Asset': self.asset_returns.columns,
            'Weight': w,
            'MargVaR': marg_var,
            'CompVaR': comp_var,
            'CompVaR%': comp_var_pct * 100
        })


