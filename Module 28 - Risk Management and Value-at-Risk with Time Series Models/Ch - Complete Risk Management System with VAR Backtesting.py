print("Loading portfolio data...")
assets = {'SPY': 0.50, 'TLT': 0.30, 'GLD': 0.10, 'USO': 0.10}

# MultiIndex extraction handling
spy_df = yf.download(list(assets.keys()), start='2010-01-01', end='2024-01-01')
if isinstance(spy_df.columns, pd.MultiIndex):
    if "Adj Close" in spy_df.columns.levels[0]:
        data = spy_df["Adj Close"].dropna()
    else:
        data = spy_df["Close"].dropna()
else:
    if "Adj Close" in spy_df.columns:
        data = spy_df["Adj Close"].dropna()
    else:
        data = spy_df["Close"].dropna()

ret_df = np.log(data / data.shift(1)).dropna()
weights = np.array([assets[col] for col in ret_df.columns])
rm = RiskMetrics(ret_df, weights=weights)

print(f"Portfolio: {assets}")
print(f"Data: {rm.T} trading days ({ret_df.index[0].date()} to {ret_df.index[-1].date()})")

# Compute VaR series
ALPHA = 0.01 # 99% VaR
WINDOW = 500 # 2-year rolling window

print(f"\nComputing VaR series (alpha={ALPHA}, window={WINDOW})...")
var_hs, es_hs = rm.historical_var(alpha=ALPHA, window=WINDOW)
var_garch, es_garch = rm.garch_var(alpha=ALPHA, dist='t', window=WINDOW)

print("\nPoint-in-Time VaR Estimates:")
pt_var, pt_es = rm.parametric_var(alpha=ALPHA)
print(f"Parametric (Normal): 99% VaR = {pt_var * 100:.2f}%, ES = {pt_es * 100:.2f}%")
print(f"Historical Sim: 99% VaR = {var_hs.iloc[-1] * 100:.2f}%, ES = {es_hs.iloc[-1] * 100:.2f}%")
print(f"GARCH-t: 99% VaR = {var_garch.iloc[-1] * 100:.2f}%, ES = {es_garch.iloc[-1] * 100:.2f}%")

# Backtest each VaR method
print("\n" + "=" * 70)
print("VaR BACKTEST RESULTS")
print("=" * 70)

backtest_results = []
violations_dict = {}

for method_name, var_series in [("Historical Sim", var_hs), ("GARCH-t", var_garch)]:
    result, viol, r_bt, v_bt = rm.backtest_var(var_series, alpha=ALPHA, name=method_name)
    backtest_results.append(result)
    violations_dict[method_name] = (viol, r_bt, v_bt)

    print(f"\n{method_name}:")
    print(f"  Observations: {result['T']}")
    print(f"  Violations: {result['Violations']} ({result['Viol_Rate'] * 100:.2f}%)")
    print(f"  Expected: {result['Expected'] * 100:.2f}%")
    print(f"  Kupiec p-value: {result['p_uc']:.4f} ({'PASS' if result['Pass_uc'] else 'FAIL'})")
    print(f"  Christoffersen: {result['p_cc']:.4f} ({'PASS' if result['Pass_cc'] else 'FAIL'})")
    print(f"  Basel (250d): {result['Viol_250d']} violations -> {result['Basel']}")

bt_df = pd.DataFrame(backtest_results)

# Component VaR
print("\n" + "=" * 50)
print("COMPONENT VaR ANALYSIS (99%, Delta-Normal)")
print("=" * 50)
comp_var_df = rm.component_var(alpha=ALPHA)
if comp_var_df is not None:
    print(comp_var_df.to_string(index=False, float_format='{:.4f}'.format))

