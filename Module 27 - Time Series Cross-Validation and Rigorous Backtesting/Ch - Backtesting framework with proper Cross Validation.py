class StrategyEvaluator:
    """
    Comprehensive strategy evaluation with statistical significance testing.
    """

    @staticmethod
    def performance_metrics(returns, rf=0.0, freq=252):
        """
        Compute full set of performance metrics.
        returns: daily return series (fraction, not %)
        rf: risk-free rate (annualized fraction)
        freq: observations per year
        """
        r = np.array(returns)
        T = len(r)

        ann_ret = r.mean() * freq
        ann_vol = r.std() * np.sqrt(freq)
        sharpe = (ann_ret - rf) / ann_vol if ann_vol > 0 else 0

        # Calmar and Sortino
        downside_vol = r[r < 0].std() * np.sqrt(freq) if (r < 0).any() else 1e-10
        sortino = (ann_ret - rf) / downside_vol

        cum = (1 + r).cumprod()
        dd = cum / np.maximum.accumulate(cum) - 1
        max_dd = dd.min()
        calmar = ann_ret / abs(max_dd) if max_dd != 0 else np.nan

        # Probabilistic Sharpe Ratio (Bailey & López de Prado, 2012)
        SR_star = 0.0
        sr_obs = r.mean() / (r.std() + 1e-10)
        sk = pd.Series(r).skew()
        ku = pd.Series(r).kurtosis()

        var_SR = (1 + 0.5 * sr_obs**2 - sk * sr_obs + (ku / 4) * sr_obs**2) / (T - 1)
        t_PSR = (sr_obs - SR_star) / np.sqrt(max(var_SR, 1e-10))
        PSR = t_dist.cdf(t_PSR, df=T - 1)

        hit_rate = (r > 0).mean()

        threshold = rf / freq
        gains = r[r >= threshold] - threshold
        losses = threshold - r[r < threshold]
        omega = gains.sum() / losses.sum() if losses.sum() > 0 else np.inf

        var99 = np.percentile(r, 1)
        es99 = r[r <= var99].mean()
        var95 = np.percentile(r, 5)
        es95 = r[r <= var95].mean()

        return {
            'Ann. Return (%)': ann_ret * 100,
            'Ann. Volatility (%)': ann_vol * 100,
            'Sharpe Ratio': sharpe,
            'Sortino Ratio': sortino,
            'Max Drawdown (%)': max_dd * 100,
            'Calmar Ratio': calmar,
            'Hit Rate (%)': hit_rate * 100,
            'Omega Ratio': omega,
            'PSR (%)': PSR * 100,
            '99% VaR (daily %)': var99 * 100,
            '99% ES (daily %)': es99 * 100,
            'Skewness': sk,
            'Excess Kurtosis': ku,
            'N Observations': T,
        }

    @staticmethod
    def deflated_sharpe_ratio(sharpes, T, skewness, kurtosis):
        """
        Deflated Sharpe Ratio (Bailey & López de Prado, 2014).
        Adjusts for multiple trials and non-normal returns.
        Returns the probability that SR > 0 after adjustment.
        """
        from scipy.special import ndtr
        n_trials = len(sharpes)
        SR_max = max(sharpes)

        euler_mascheroni = 0.5772156649
        expected_max = ((1 - euler_mascheroni) * t_dist.ppf(1 - 1 / n_trials, df=T - 1)
                        + euler_mascheroni * t_dist.ppf(1 - 1 / (n_trials * np.e), df=T - 1))

        SR_benchmark = expected_max * np.sqrt(1 / T * (1 + 0.5 * SR_max**2 - skewness * SR_max + kurtosis * SR_max**2 / 4))
        var_SR = (1 + 0.5 * SR_max**2 - skewness * SR_max + kurtosis * SR_max**2 / 4) / (T - 1)
        t_stat = (SR_max - SR_benchmark) / np.sqrt(max(var_SR, 1e-10))
        return float(ndtr(t_stat))

    @staticmethod
    def diebold_mariano_test(errors1, errors2, h=1):
        """
        Diebold-Mariano test (1995) for equal predictive accuracy.
        """
        d = np.array(errors1) - np.array(errors2)
        T = len(d)
        d_bar = d.mean()

        gamma0 = np.var(d, ddof=1)
        gamma_sum = 0
        for j in range(1, h):
            gamma_j = np.mean((d[j:] - d_bar) * (d[:-j] - d_bar))
            gamma_sum += (1 - j / h) * gamma_j
        V_d = (gamma0 + 2 * gamma_sum) / T

        DM = d_bar / np.sqrt(max(V_d, 1e-12))
        p_val = 2 * (1 - t_dist.cdf(abs(DM), df=T - 1))
        return float(DM), float(p_val)

