class PurgedKFold(BaseCrossValidator):
    """
    Purged K-Fold cross-validation for financial time series.
    Adds an embargo gap between training and testing to prevent leakage.

    Reference: López de Prado (2018), Advances in Financial Machine Learning
    """
    def __init__(self, n_splits=5, embargo_pct=0.02):
        """
        n_splits: number of CV splits
        embargo_pct: fraction of training set size to use as embargo gap
        """
        self.n_splits = n_splits
        self.embargo_pct = embargo_pct

    def split(self, X, y=None, groups=None):
        n = len(X)
        fold_size = n // self.n_splits
        embargo = int(n * self.embargo_pct)

        indices = np.arange(n)
        for k in range(self.n_splits):
            # Test set: k-th fold
            test_start = k * fold_size
            test_end = (k+1) * fold_size if k < self.n_splits - 1 else n
            test_idx = indices[test_start:test_end]

            # Train set: all data outside test fold, with embargo
            train_end = max(0, test_start - embargo)
            train_idx = indices[:train_end]
            if len(train_idx) < 2 * fold_size:
                continue

            yield train_idx, test_idx

    def get_n_splits(self, X=None, y=None, groups=None):
        return self.n_splits


class WalkForwardCV:
    """
    Walk-forward (expanding window) cross-validation for time series.
    Supports both expanding and rolling windows.
    """
    def __init__(self, initial_train_pct=0.4, test_pct=0.1, step_pct=0.05, window_type='expanding'):
        """
        initial_train_pct: fraction of data for initial training set
        test_pct: fraction of data for each test fold
        step_pct: fraction of data to step forward each fold
        window_type: 'expanding' or 'rolling'
        """
        self.init_train = initial_train_pct
        self.test_frac = test_pct
        self.step = step_pct
        self.window = window_type

    def split(self, X):
        n = len(X)
        init_end = int(n * self.init_train)
        test_size = int(n * self.test_frac)
        step_size = int(n * self.step)

        splits = []
        train_end = init_end
        while train_end + test_size <= n:
            test_start = train_end
            test_end = min(train_end + test_size, n)

            if self.window == 'expanding':
                train_start = 0
            else: # rolling
                train_start = max(0, train_end - init_end)

            train_idx = np.arange(train_start, train_end)
            test_idx = np.arange(test_start, test_end)
            if len(train_idx) > 10 and len(test_idx) > 0:
                splits.append((train_idx, test_idx))

            train_end += step_size

        return splits

