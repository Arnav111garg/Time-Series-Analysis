# PART 3: COMPREHENSIVE BACKTEST EXAMPLE
#

print("Loading data for backtesting demonstration...")
spy_df = yf.download("SPY", start="2004-01-01", end="2024-01-01")

# Safely extract Close/Adj Close depending on what yfinance returns
if isinstance(spy_df.columns, pd.MultiIndex):
    if "Adj Close" in spy_df.columns.levels[0]:
        spy = spy_df["Adj Close"]["SPY"]
    else:
        spy = spy_df["Close"]["SPY"]
else:
    if "Adj Close" in spy_df.columns:
        spy = spy_df["Adj Close"]
    else:
        spy = spy_df["Close"]

r = np.log(spy / spy.shift(1)).dropna()

# Feature engineering
features = pd.DataFrame(index=r.index)
for w in [5, 10, 21, 63]:
    features[f'mom_{w}d'] = r.rolling(w).mean()
    features[f'vol_{w}d'] = r.rolling(w).std()
features['vol_ratio'] = features['vol_5d'] / (features['vol_21d'] + 1e-10)
features['rsi'] = (100 - 100 / (1 + r.clip(lower=0).ewm(com=13).mean() / r.clip(upper=0).abs().ewm(com=13).mean())) / 50 - 1
features = features.dropna()
r_aligned = r.reindex(features.index)

X = features.values
y = r_aligned.values
n = len(X)

# Run walk-forward backtest
print("Running walk-forward backtests...")
wfcv = WalkForwardCV(initial_train_pct=0.35, test_pct=0.10, step_pct=0.03)
splits = wfcv.split(X)

all_predictions = np.full(n, np.nan)
all_true = y.copy()
fold_results = []

evaluator = StrategyEvaluator()

for fold_num, (train_idx, test_idx) in enumerate(splits):
    X_tr, y_tr = X[train_idx], y[train_idx]
    X_te, y_te = X[test_idx], y[test_idx]

    # Fit scaler on train only
    scaler = StandardScaler()
    X_tr_s = scaler.fit_transform(X_tr)
    X_te_s = scaler.transform(X_te)

    # Fit regularized linear model
    alphas = np.logspace(-3, 2, 30)
    ridge = RidgeCV(alphas=alphas, cv=3, scoring='neg_mean_squared_error')
    ridge.fit(X_tr_s, y_tr)

    preds = ridge.predict(X_te_s)
    all_predictions[test_idx] = preds

    # Fold performance
    signal = np.sign(preds)
    pnl = signal * y_te
    pnl_tc = pnl - 0.0005 * np.abs(np.diff(np.concatenate([[0], signal])))

    fold_results.append({
        'fold': fold_num,
        'train_n': len(train_idx),
        'test_n': len(test_idx),
        'test_start': features.index[test_idx[0]],
        'test_end': features.index[test_idx[-1]],
        'RMSE': np.sqrt(mean_squared_error(y_te, preds)),
        'IC': np.corrcoef(preds, y_te)[0, 1],
        'Sharpe': pnl.mean() * np.sqrt(252) / (pnl.std() * np.sqrt(252) + 1e-10) * np.sqrt(252),
        'Sharpe_net': pnl_tc.mean() * np.sqrt(252) / (pnl_tc.std() * np.sqrt(252) + 1e-10) * np.sqrt(252),
    })

folds_df = pd.DataFrame(fold_results)
print(f"\nWalk-Forward Backtest Results ({len(splits)} folds):")
print(folds_df[['test_start', 'test_end', 'IC', 'Sharpe', 'Sharpe_net']].to_string(index=False))

# Aggregate OOS performance
valid_mask = ~np.isnan(all_predictions)
oos_preds = all_predictions[valid_mask]
oos_true = all_true[valid_mask]
oos_idx = features.index[valid_mask]

oos_signal = np.sign(oos_preds)
oos_pnl = oos_signal * oos_true
oos_tc = 0.0005 * np.abs(np.diff(np.concatenate([[0], oos_signal])))
oos_net = oos_pnl - oos_tc

# Benchmark: buy and hold
bh_pnl = oos_true

print("\n" + "=" * 60)
print("AGGREGATE OUT-OF-SAMPLE PERFORMANCE")
print("=" * 60)
for label, pnls in [("Ridge Signal (gross)", oos_pnl),
                    ("Ridge Signal (net TC)", oos_net),
                    ("Buy & Hold", bh_pnl)]:
    metrics = evaluator.performance_metrics(pnls)
    print(f"\n{label}:")
    for key in ['Ann. Return (%)', 'Ann. Volatility (%)', 'Sharpe Ratio',
                'Max Drawdown (%)', 'Hit Rate (%)', 'PSR (%)', 'Skewness']:
        print(f"  {key:<25}: {metrics[key]:>8.3f}")

# Diebold-Mariano test
naive_preds = np.zeros(len(oos_preds))
err_ridge = (oos_preds - oos_true) ** 2
err_naive = (naive_preds - oos_true) ** 2
DM_stat, DM_p = evaluator.diebold_mariano_test(err_naive, err_ridge)
print(f"\nDiebold-Mariano Test (H0: Ridge = Naive):")
print(f"  DM statistic: {DM_stat:.4f}")
print(f"  p-value: {DM_p:.4f} ({'Significant' if DM_p < 0.05 else 'Not significant'})")

# Information Coefficient (IC) analysis
monthly_ic = []
monthly_dates = []
for month_start in pd.date_range(oos_idx[0], oos_idx[-1], freq='MS'):
    month_end = month_start + pd.offsets.MonthEnd()
    mask = (oos_idx >= month_start) & (oos_idx <= month_end)
    if mask.sum() > 10:
        monthly_ic.append(np.corrcoef(oos_preds[mask], oos_true[mask])[0, 1])
        monthly_dates.append(month_start)

ic_series = pd.Series(monthly_ic, index=monthly_dates)
ICIR = ic_series.mean() / (ic_series.std() + 1e-10)
print(f"\nInformation Coefficient (IC) Analysis:")
print(f"  Mean Monthly IC: {ic_series.mean():.4f}")
print(f"  IC Std: {ic_series.std():.4f}")
print(f"  ICIR (IC/IC_std): {ICIR:.4f}")
print(f"  % months IC > 0: {(ic_series > 0).mean() * 100:.1f}%")

# Visualization
fig = plt.figure(figsize=(16, 16))
gs = fig.add_gridspec(4, 3, hspace=0.45, wspace=0.35)

