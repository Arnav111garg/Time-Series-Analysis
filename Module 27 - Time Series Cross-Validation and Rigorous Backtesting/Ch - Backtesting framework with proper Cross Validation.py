ax2.axvline(ic_series.mean(), color='red', lw=2, label=f'Mean={ic_series.mean():.3f}')
ax2.axvline(0, color='k', lw=0.8, linestyle='--')
ax2.set_title(f"Monthly IC Distribution\n(ICIR={ICIR:.3f})")
ax2.legend(fontsize=9)

# 3. Cumulative returns
ax3 = fig.add_subplot(gs[1, :])
cum_signal = (1 + pd.Series(oos_net, index=oos_idx)).cumprod()
cum_bh = (1 + pd.Series(bh_pnl, index=oos_idx)).cumprod()
ax3.plot(cum_signal.index, cum_signal.values, 'darkgreen', lw=2, label='Ridge Strategy (net TC)')
ax3.plot(cum_bh.index, cum_bh.values, 'navy', lw=1.5, linestyle='--', label='Buy & Hold')
