# Quantifying the asymmetry in volatility response
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from statsmodels.regression.linear_model import OLS
from statsmodels.tools import add_constant

spx_df = yf.download("^GSPC", start="1990-01-01", end="2024-01-01", auto_adjust=False)
spx = spx_df["Adj Close"].squeeze()
r = 100 * np.log(spx / spx.shift(1)).dropna()

rv5 = r.rolling(5).var().shift(-5)
abs_r = r.abs()
q75 = abs_r.quantile(0.75)

df = pd.DataFrame({
    'rv_fwd': rv5,
    'r_neg': r.clip(upper=0),
    'r_pos': r.clip(lower=0),
    'r_sq': r**2,
    'r_neg_big': (r < -q75).astype(float) * abs_r,
    'r_pos_big': (r > q75).astype(float) * abs_r,
    'r_neg_sml': ((r < 0) & (abs_r < q75)).astype(float) * abs_r,
    'r_pos_sml': ((r > 0) & (abs_r < q75)).astype(float) * abs_r,
}).dropna()

X = add_constant(df[['r_neg_big', 'r_pos_big', 'r_neg_sml', 'r_pos_sml']])
y = df['rv_fwd']
reg = OLS(y, X).fit()
print(reg.summary())

R = np.array([[0, 1, -1, 0, 0]])
wald = reg.f_test(R)
print(f"\nWald test (neg_big = pos_big): F={wald.fvalue:.4f}, p={wald.pvalue:.6f}")

n_bins = 20
r_quantiles = pd.qcut(r, q=n_bins, labels=False)
avg_fvol = rv5.groupby(r_quantiles).mean()

plt.figure(figsize=(10, 5))
plt.bar(range(n_bins), avg_fvol.values,
        color=['firebrick' if i < n_bins // 2 else 'steelblue' for i in range(n_bins)],
        edgecolor='k', linewidth=0.4)
plt.xlabel("Return Quantile (1=most negative, 20=most positive)")
plt.ylabel("Average Next-5-Day Variance")
plt.title("Asymmetric Volatility Response: SPX 1990-2024\n(Red = negative return days, Blue = positive return days)")
plt.axvline(n_bins / 2 - 0.5, color='k', linestyle='--')
plt.tight_layout()
plt.savefig("asymmetry_response.pdf", dpi=150)
plt.show()
print("\nAverage next-5-day variance by decile:")
for i in[0,1,2,8,9]:
  print(f"Q{i+1:02d}:{avg_fvol.values[i]:.4f}")

