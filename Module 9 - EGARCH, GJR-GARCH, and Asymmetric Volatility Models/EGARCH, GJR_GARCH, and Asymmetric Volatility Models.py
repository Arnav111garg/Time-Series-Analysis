# Full GARCH family comparison on SPX
import numpy as np
import pandas as pd
import yfinance as yf
from arch import arch_model
import warnings
warnings.filterwarnings('ignore')

spx_df = yf.download("^GSPC", start="1990-01-01", end="2024-01-01", auto_adjust=False)
spx = spx_df["Adj Close"].squeeze()
r = 100 * np.log(spx / spx.shift(1)).dropna()

models_spec = {
    'ARCH(5)': dict(vol='ARCH', p=5, dist='normal'),
    'GARCH(1,1)-N': dict(vol='GARCH', p=1, q=1, dist='normal'),
    'GARCH(1,1)-t': dict(vol='GARCH', p=1, q=1, dist='t'),
    'GARCH(1,1)-SkewT': dict(vol='GARCH', p=1, q=1, dist='skewt'),
    'GARCH(2,1)-t': dict(vol='GARCH', p=2, q=1, dist='t'),
    'GARCH(1,2)-t': dict(vol='GARCH', p=1, q=2, dist='t'),
    'GJR-GARCH(1,1)-t': dict(vol='GARCH', p=1, o=1, q=1, dist='t'),
    'EGARCH(1,1)-t': dict(vol='EGARCH', p=1, o=1, q=1, dist='t'),
    'EGARCH(1,1)-SkewT': dict(vol='EGARCH', p=1, o=1, q=1, dist='skewt'),
    'APARCH(1,1)-t': dict(vol='APARCH', p=1, q=1, dist='t'),
}

results = {}
for name, spec in models_spec.items():
    try:
        mdl = arch_model(r, mean='Constant', **spec)
        fit = mdl.fit(disp='off', options={'maxiter': 1000})
        results[name] = {
            'AIC': fit.aic,
            'BIC': fit.bic,
            'LogL': fit.loglikelihood,
            'Params': len(fit.params),
            'alpha+beta': sum(v for k, v in fit.params.items()
                             if 'alpha' in k.lower() or 'beta' in k.lower()),
        }
    except Exception as e:
        results[name] = {
            'AIC': np.nan,
            'BIC': np.nan,
            'LogL': np.nan,
            'Params': np.nan,
            'alpha+beta': np.nan
        }

df_res = pd.DataFrame(results).T.sort_values('BIC')
df_res['dBIC'] = df_res['BIC'] - df_res['BIC'].min()
print("\nGARCH Model Comparison (SPX 1990-2024):")
print(df_res[['AIC', 'BIC', 'dBIC', 'LogL', 'Params']])

