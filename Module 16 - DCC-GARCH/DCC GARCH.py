import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.cm as cm
import yfinance as yf
from arch import arch_model
from scipy.optimize import minimize
from scipy.linalg import cholesky
import warnings
warnings.filterwarnings('ignore')

# Download multi-asset returns
tickers = {
    'SPY': 'S&P 500',
    'TLT': '20Y Treasury',
    'GLD': 'Gold',
    'USO': 'Oil',
    'EFA': 'Int. Equity'
}
raw_data = yf.download(list(tickers.keys()), start='2007-01-01', end='2024-01-01', progress=False)

# Secure clean extraction of Close prices avoiding MultiIndex extraction errors
if isinstance(raw_data.columns, pd.MultiIndex):
    data = raw_data['Adj Close'] if 'Adj Close' in raw_data.columns.levels[0] else raw_data['Close']
else:
    data = raw_data['Adj Close'] if 'Adj Close' in raw_data.columns else raw_data['Close']

data = data.dropna()
ret = 100 * np.log(data / data.shift(1)).dropna()

K = ret.shape[1]
T = ret.shape[0]
print(f"Dataset: {K} assets, {T} observations, {ret.index[0].date()} to {ret.index[-1].date()}")

#
# STEP 1: Fit univariate GARCH(1,1)-t to each series
#
garch_fits = {}
std_resids = pd.DataFrame(index=ret.index, columns=ret.columns)
cond_vols = pd.DataFrame(index=ret.index, columns=ret.columns)

print("\nFitting univariate GARCH(1,1)-t models:")
for col in ret.columns:
    try:
        mdl = arch_model(ret[col], vol='GARCH', p=1, q=1, dist='t')
        fit = mdl.fit(disp='off')
        garch_fits[col] = fit
        std_resids[col] = fit.resid / fit.conditional_volatility
        cond_vols[col] = fit.conditional_volatility
        print(f"  {col}: alpha={fit.params['alpha[1]']:.4f}, beta={fit.params['beta[1]']:.4f}, nu={fit.params.get('nu', np.nan):.2f}")
    except Exception as e:
        print(f"  {col}: FAILED ({e})")

std_resids = std_resids.astype(float).dropna()
cond_vols = cond_vols.astype(float).loc[std_resids.index]
Z = std_resids.values  # T x K

#
# STEP 2: DCC Estimation
#
Q_bar = (Z.T @ Z) / len(Z)  # unconditional correlation (approx)

def dcc_filter(Z, a, b, Q_bar):
    """Compute DCC filter given standardized residuals and parameters."""
    T, K = Z.shape
    Q_t = np.zeros((T, K, K))
    R_t = np.zeros((T, K, K))
    Q_t[0] = Q_bar.copy()

    for t in range(1, T):
        Q_t[t] = (1 - a - b) * Q_bar + a * np.outer(Z[t - 1], Z[t - 1]) + b * Q_t[t - 1]
        D_inv = np.diag(1.0 / np.sqrt(np.diag(Q_t[t])))
        R_t[t] = D_inv @ Q_t[t] @ D_inv
        np.fill_diagonal(R_t[t], 1.0)

    return R_t, Q_t

def dcc_loglik(params, Z, Q_bar):
    """DCC step-2 log-likelihood (negative for minimization)."""
    a, b = params
    if a <= 0 or b <= 0 or a + b >= 1:
        return 1e10
    T, K = Z.shape
    R_t, _ = dcc_filter(Z, a, b, Q_bar)
    ll = 0
    for t in range(1, T):
        try:
            R = R_t[t]
            log_det = np.log(np.linalg.det(R) + 1e-12)
            R_inv = np.linalg.inv(R)
            z = Z[t]
            ll += -0.5 * (log_det + z @ R_inv @ z - z @ z)
        except np.linalg.LinAlgError:
            return 1e10
    return -ll

print("\nEstimating DCC parameters...")
opt = minimize(
    dcc_loglik, x0=[0.03, 0.95], args=(Z, Q_bar),
    method='L-BFGS-B',
    bounds=[(1e-4, 0.5), (1e-4, 0.9998)],
    options={'maxiter': 1000, 'ftol': 1e-10}
)

a_hat, b_hat = opt.x
print(f"DCC estimates: a={a_hat:.4f}, b={b_hat:.4f}")
print(f"DCC persistence: a+b = {a_hat + b_hat:.4f}")
print(f"Mean reversion half-life: {-np.log(2) / np.log(a_hat + b_hat):.1f} days")

# Compute DCC correlations
R_t, Q_t = dcc_filter(Z, a_hat, b_hat, Q_bar)

#
# STEP 3: Visualize dynamic correlations
#
dates = std_resids.index
asset_pairs = [(0, 1, 'SPY-TLT'), (0, 2, 'SPY-GLD'), (0, 3, 'SPY-USO'), (1, 2, 'TLT-GLD')]

fig, axes = plt.subplots(len(asset_pairs), 1, figsize=(14, 3.5 * len(asset_pairs)), sharex=True)
fig.suptitle("DCC-GARCH(1,1) Dynamic Conditional Correlations", fontsize=14, fontweight='bold')

for idx, (i, j, label) in enumerate(asset_pairs):
    corr_ij = R_t[1:, i, j]  # start from t=1
    rolling_corr = pd.Series(Z[:, i], index=dates).rolling(63).corr(pd.Series(Z[:, j], index=dates))

    axes[idx].plot(dates[1:], corr_ij, 'navy', lw=0.8, label='DCC Correlation')
    axes[idx].plot(rolling_corr.index, rolling_corr.values, 'firebrick', lw=0.8, alpha=0.6, linestyle='--', label='63-day Rolling Corr')
    axes[idx].axhline(0, color='k', lw=0.5, linestyle=':')
    axes[idx].axhline(Q_bar[i, j] / np.sqrt(Q_bar[i, i] * Q_bar[j, j]), color='gray', lw=1, linestyle='-.', label='Unconditional Corr')

    # Shade GFC and COVID recessions
    for (s, e, col) in [('2008-09-01', '2009-03-31', '#FF000020'), ('2020-02-01', '2020-06-30', '#FF880020')]:
        axes[idx].axvspan(pd.Timestamp(s), pd.Timestamp(e), facecolor=col, edgecolor='none')

    axes[idx].set_title(f"{label}", fontsize=10)
    axes[idx].set_ylabel("Correlation")
    axes[idx].legend(fontsize=8, loc='upper right')
    axes[idx].set_ylim(-1.1, 1.1)

plt.tight_layout()
plt.savefig("dcc_correlations.pdf", dpi=150)
plt.show()

#
# STEP 4: DCC-based minimum variance portfolio
#
print("\n=== DCC Minimum Variance Portfolio ===")

# Construct daily H_t = D_t * R_t * D_t
D_t = cond_vols.values[1:]  # T x K conditional volatilities
H_t = np.zeros((T - 1, K, K))
for t in range(T - 1):
    D = np.diag(D_t[t])
    H_t[t] = D @ R_t[t + 1] @ D

# Minimum variance weights
def mv_weights(H):
    K = H.shape[0]
    inv_H = np.linalg.inv(H + 1e-8 * np.eye(K))
    ones = np.ones(K)
    w = inv_H @ ones
    return w / (ones @ w)

weights = np.array([mv_weights(H_t[t]) for t in range(T - 1)])
w_df = pd.DataFrame(weights, columns=ret.columns, index=ret.index[1:len(H_t) + 1])

# Portfolio returns
aligned_ret = ret.iloc[1:len(H_t) + 1]
port_ret = (aligned_ret.values * weights[:len(aligned_ret)]).sum(axis=1)
port_ret = pd.Series(port_ret, index=aligned_ret.index)

# Benchmark: equal weight
eq_ret = aligned_ret.mean(axis=1)

# Performance comparison
def sharpe(r):
    return r.mean() * np.sqrt(252) / (r.std() if r.std() > 0 else 1.0)
def maxdd(r):
    c = (1 + r / 100).cumprod()
    return (c / c.cummax() - 1).min()

print(f"\n{'Strategy': <25} {'Ann. Ret%':>10} {'Ann. Vol%':>10} {'Sharpe':>8} {'MaxDD%':>8}")
print('-' * 65)
for name, r_s in [('DCC Min-Var', port_ret), ('Equal Weight', eq_ret)]:
    ar = r_s.mean() * 252
    av = r_s.std() * np.sqrt(252)
    sr = ar / av if av > 0 else 0.0
    dd = maxdd(r_s)
    print(f"{name:<25} {ar:>10.2f} {av:>10.2f} {sr:>8.3f} {dd*100:>8.2f}")

# Plot weights over time
fig, axes = plt.subplots(2, 1, figsize=(14, 8), sharex=True)
axes[0].stackplot(
    w_df.index, w_df.T.values,
    labels=w_df.columns.tolist(),
    colors=cm.tab10(np.linspace(0, 1, K)), alpha=0.85
)
axes[0].set_title("DCC-GARCH Minimum Variance Portfolio Weights Over Time")
axes[0].set_ylabel("Weight")
axes[0].legend(loc='upper right', fontsize=9)

cum_port = (1 + port_ret / 100).cumprod()
cum_eq = (1 + eq_ret / 100).cumprod()
axes[1].plot(cum_port.index, cum_port.values, 'darkgreen', lw=2, label=f'DCC Min-Var (Sharpe={sharpe(port_ret):.2f})')
axes[1].plot(cum_eq.index, cum_eq.values, 'firebrick', lw=1.5, linestyle='--', label=f'Equal Weight (Sharpe={sharpe(eq_ret):.2f})')
axes[1].set_yscale('log')
axes[1].set_title("Cumulative Portfolio Return (log scale)")
axes[1].legend()
axes[1].set_ylabel("Wealth")

plt.tight_layout()
plt.savefig("dcc_portfolio.pdf", dpi=150)
plt.show()