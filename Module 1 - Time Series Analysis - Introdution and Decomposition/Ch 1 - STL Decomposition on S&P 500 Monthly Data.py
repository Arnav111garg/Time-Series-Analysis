import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import yfinance as yf
from statsmodels.tsa.seasonal import STL, seasonal_decompose

spx = yf.download("^GSPC", start="2000-01-01", end="2024-01-01", interval="1mo", auto_adjust=False)["Adj Close"]
spx = spx.dropna()
log_spx = np.log(spx)
classical = seasonal_decompose(log_spx, model='additive', period=12)

fig, axes = plt.subplots(4, 1, figsize=(14, 10), sharex=True)
classical.observed.plot(ax=axes[0], color='navy'); axes[0].set_ylabel('Observed')
classical.trend.plot(ax=axes[1], color='crimson'); axes[1].set_ylabel('Trend')
classical.seasonal.plot(ax=axes[2], color='seagreen'); axes[2].set_ylabel('Seasonal')
classical.resid.plot(ax=axes[3], color='gray'); axes[3].set_ylabel('Residual')
fig.suptitle('Classical Decomposition: Log SPX (Monthly)', fontsize=14, fontweight='bold')
plt.tight_layout(); plt.savefig('classical_decomp.pdf', dpi=150)

k = STL(log_spx, period=12, robust=True)
stl_result = k.fit()

fig2, axes2 = plt.subplots(4, 1, figsize=(14, 10), sharex=True)
axes2[0].plot(stl_result.observed, color='navy'); axes2[0].set_ylabel('Observed')
axes2[1].plot(stl_result.trend, color='crimson'); axes2[1].set_ylabel('Trend')
axes2[2].plot(stl_result.seasonal, color='seagreen'); axes2[2].set_ylabel('Seasonal')
axes2[3].plot(stl_result.resid, color='gray'); axes2[3].set_ylabel('Residual')
fig2.suptitle('STL Decomposition: Log SPX (Monthly)', fontsize=14, fontweight='bold')
plt.tight_layout(); plt.savefig('stl_decomp.pdf', dpi=150)

resid = stl_result.resid.dropna()
seasonal = stl_result.seasonal
F_s = max(0, 1 - np.var(resid) / np.var(seasonal + resid))
print(f"Seasonal strength (0=none, 1=pure): {F_s:.4f}")

