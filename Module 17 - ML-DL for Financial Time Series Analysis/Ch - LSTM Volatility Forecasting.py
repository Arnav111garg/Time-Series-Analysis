import numpy as np
import pandas as pd
import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader
import yfinance as yf
from sklearn.metrics import mean_squared_error, mean_absolute_error
import warnings
warnings.filterwarnings('ignore')

# Dataset
spy = yf.download("SPY", start="2000-01-01", end="2024-01-01", progress=False)
# Handle MultiIndex columns safely
if isinstance(spy.columns, pd.MultiIndex):
    spy_close = spy['Adj Close']['SPY'].squeeze() if 'Adj Close' in spy.columns.get_level_values(0) else spy['Close']['SPY'].squeeze()
else:
    spy_close = spy['Adj Close'].squeeze() if 'Adj Close' in spy.columns else spy['Close'].squeeze()

ret = 100 * np.log(spy_close / spy_close.shift(1)).dropna()

# Target : 5-day ahead realized vol
rv5d = ret.rolling(5).std().shift(-5) * np.sqrt(252)
rv5d = rv5d.dropna()

# Features: lagged returns and vol
def create_vol_features(ret, rv5d, lookback=60):
    """ Creates sequences for LSTM vol forecasting. """
    rv1d = ret.rolling(5).std() * np.sqrt(252)
    rv5d_hist = ret.rolling(5).std().rolling(5).mean() * np.sqrt(252)

    feat = pd.concat([
        ret, rv1d,
        ret.abs(), rv5d_hist
    ], axis=1).dropna()
    feat.columns = ['ret', 'rv1d', 'abs_ret', 'rv5d_hist']

    target = rv5d

    # Align
    common_idx = feat.index.intersection(target.index)
    feat = feat.loc[common_idx]
    target = target.loc[common_idx]

    # Normalize features (rolling z-score to avoid lookahead)
    feat_norm = (feat - feat.rolling(252).mean()) / (feat.rolling(252).std() + 1e-10)
    feat_norm = feat_norm.dropna()
    target = target.loc[feat_norm.index]

    # Create sequences
    X, y = [], []
    arr_f = feat_norm.values
    arr_t = target.values
    for i in range(lookback, len(arr_f)):
        X.append(arr_f[i-lookback:i])
        y.append(arr_t[i])
    return np.array(X, dtype=np.float32), np.array(y, dtype=np.float32)

X_seq, y_seq = create_vol_features(ret, rv5d)
print(f"Sequence data: X={X_seq.shape}, y={y_seq.shape}")

# Train/Val/Test split (no shuffling!)
T = len(X_seq)
train_end = int(0.7 * T)
val_end = int(0.85 * T)

X_train, y_train = X_seq[:train_end], y_seq[:train_end]
X_val, y_val = X_seq[train_end:val_end], y_seq[train_end:val_end]
X_test, y_test = X_seq[val_end:], y_seq[val_end:]

class TimeSeriesDataset(Dataset):
    def __init__(self, X, y):
        self.X = torch.FloatTensor(X)
        self.y = torch.FloatTensor(y).unsqueeze(1)
    def __len__(self):
        return len(self.X)
    def __getitem__(self, i):
        return self.X[i], self.y[i]

train_dl = DataLoader(TimeSeriesDataset(X_train, y_train), batch_size=64, shuffle=False)
val_dl = DataLoader(TimeSeriesDataset(X_val, y_val), batch_size=64, shuffle=False)

# LSTM Model
class VolLSTM(nn.Module):
    """
    LSTM for volatility forecasting.
    Dropout for regularization, skip connection for stability.
    """
    def __init__(self, input_size=4, hidden_size=64, num_layers=2, dropout=0.3, output_size=1):
        super().__init__()
        self.lstm = nn.LSTM(input_size, hidden_size, num_layers=num_layers,
                            batch_first=True, dropout=dropout if num_layers > 1 else 0)
        self.dropout = nn.Dropout(dropout)
        self.fc1 = nn.Linear(hidden_size, 32)
        self.fc2 = nn.Linear(32, output_size)
        self.relu = nn.ReLU()

    def forward(self, x):
        out, _ = self.lstm(x) # (batch, seq, hidden)
        out = out[:, -1, : ] # take last time step
        out = self.dropout(out)
        out = self.relu(self.fc1(out))
        return self.fc2(out)

device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
model = VolLSTM(input_size=X_seq.shape[2]).to(device)
print(f"\nModel parameters: {sum(p.numel() for p in model.parameters()):,}")
print(f"Device: {device}")

# Training
optimizer = torch.optim.Adam(model.parameters(), lr=1e-3, weight_decay=1e-4)
# Removed 'verbose=False' as it is an unexpected keyword argument in newer PyTorch versions
scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(optimizer, patience=10, factor=0.5)
criterion = nn.MSELoss()

train_losses, val_losses = [], []
best_val_loss = np.inf
patience_counter = 0
early_stop_patience = 25

for epoch in range(200):
    model.train()
    ep_loss = 0
    for Xb, yb in train_dl:
        Xb, yb = Xb.to(device), yb.to(device)
        optimizer.zero_grad()
        pred = model(Xb)
        loss = criterion(pred, yb)
        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), 1.0) # gradient clipping
        optimizer.step()
        ep_loss += loss.item()
    train_losses.append(ep_loss / len(train_dl))

    # Validation
    model.eval()
    with torch.no_grad():
        val_loss = sum(criterion(model(Xb.to(device)), yb.to(device)).item() for Xb, yb in val_dl) / len(val_dl)
    val_losses.append(val_loss)
    scheduler.step(val_loss)

    if val_loss < best_val_loss:
        best_val_loss = val_loss
        torch.save(model.state_dict(), 'best_lstm.pt')
        patience_counter = 0
    else:
        patience_counter += 1

    if patience_counter >= early_stop_patience:
        print(f"Early stopping at epoch {epoch}")
        break

    if (epoch+1) % 20 == 0:
        print(f"Epoch {epoch+1:3d}: Train={train_losses[-1]:.4f}, Val={val_losses[-1]:.4f}")

# Test Evaluation
model.load_state_dict(torch.load('best_lstm.pt', map_location=device))
model.eval()

with torch.no_grad():
    X_test_t = torch.FloatTensor(X_test).to(device)
    preds_lstm = model(X_test_t).cpu().numpy().flatten()

rmse_lstm = np.sqrt(mean_squared_error(y_test, preds_lstm))
mae_lstm = mean_absolute_error(y_test, preds_lstm)
corr_lstm = np.corrcoef(y_test, preds_lstm)[0, 1]

# Benchmark: simple HAR (last 5-day avg)
naive_pred = np.mean(X_test[:, -5:, 1], axis=1) # rv1d feature avg
rmse_naive = np.sqrt(mean_squared_error(y_test, naive_pred))

print(f"\n{'='*50}")
print("TEST SET EVALUATION")
print(f"{'='*50}")
print(f"LSTM: RMSE={rmse_lstm:.4f}, MAE={mae_lstm:.4f}, Corr={corr_lstm:.4f}")
print(f"Naive: RMSE={rmse_naive:.4f}")
print(f"LSTM skill over naive: {((rmse_naive - rmse_lstm) / rmse_naive) * 100:.1f}%")

