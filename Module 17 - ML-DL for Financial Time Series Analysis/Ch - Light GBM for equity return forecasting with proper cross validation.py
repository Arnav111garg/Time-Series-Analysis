# CRITICAL: Time-series cross-validation (NO LEAKAGE)
class TimeSeriesPurgedCV:
    def __init__(self, n_splits=5, embargo_days=21):
        self.n_splits = n_splits
        self.embargo = embargo_days

    def split(self, X, y=None, groups=None):
        T = len(X)
        fold_size = T // self.n_splits
        for k in range(self.n_splits):
            test_start = k * fold_size
            test_end = (k + 1) * fold_size
            train_end = max(0, test_start - self.embargo)
            if train_end > 0 and test_end <= T:
                yield np.arange(0, train_end), np.arange(test_start, test_end)

def walk_forward_validation(X, y, model, n_splits=10):
    """
    Walk-forward (expanding window) validation for time series.
    """
    T = len(X)
    min_train = T // 3  # use first 1/3 for initial training
    step_size = (T - min_train) // n_splits

    all_preds = np.full(T, np.nan)
    all_true = y.copy()

    for k in range(n_splits):
        train_end = min_train + k * step_size
        test_start = train_end
        test_end = min(train_end + step_size, T)

        if test_end <= test_start:
            break

        X_train, y_train = X[:train_end], y[:train_end]
        X_test = X[test_start:test_end]

        model.fit(X_train, y_train)
        all_preds[test_start:test_end] = model.predict(X_test)

    return all_preds

