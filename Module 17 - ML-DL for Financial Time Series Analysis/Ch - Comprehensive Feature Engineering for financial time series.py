import numpy as np
import pandas as pd
import yfinance as yf
import matplotlib.pyplot as plt
from scipy.stats import skew, kurtosis
import warnings
warnings.filterwarnings('ignore')

def create_features(ticker, start='2000-01-01', end='2024-01-01'):
    """
    Create a comprehensive feature matrix for ML-based forecasting.
    Target: forward 1-day return (classification: up/down, or regression).
    """
    raw = yf.download(ticker, start=start, end=end, progress=False)
    df = pd.DataFrame()

    # Flatten or safely handle MultiIndex columns
    if isinstance(raw.columns, pd.MultiIndex):
        # Extract specific column using cross-section or indexing
        close = raw['Close'][ticker] if 'Close' in raw.columns.get_level_values(0) else raw['Adj Close'][ticker]
        volume = raw['Volume'][ticker]
        high = raw['High'][ticker]
        low = raw['Low'][ticker]
        opn = raw['Open'][ticker]
    else:
        close = raw['Close'] if 'Close' in raw.columns else raw['Adj Close']
        volume = raw['Volume']
        high = raw['High']
        low = raw['Low']
        opn = raw['Open']

    # Ensure we are working with Series
    close = close.squeeze()
    volume = volume.squeeze()
    high = high.squeeze()
    low = low.squeeze()
    opn = opn.squeeze()

    df['ret_1d'] = np.log(close / close.shift(1))
    df['ret_2d'] = np.log(close / close.shift(2))
    df['ret_5d'] = np.log(close / close.shift(5))
    df['ret_10d'] = np.log(close / close.shift(10))
    df['ret_21d'] = np.log(close / close.shift(21))
    df['ret_63d'] = np.log(close / close.shift(63))

    # Volatility features
    for w in [5, 10, 21, 63]:
        df[f'rv_{w}d'] = df['ret_1d'].rolling(w).std() * np.sqrt(252)
        df[f'rvol_norm_{w}d'] = df['ret_1d'].rolling(w).std() / df['ret_1d'].rolling(63).std()

    # Realized vol ratio (short / long): identifies vol regime
    df['vol_ratio_5_63'] = df['rv_5d'] / df['rv_63d']
    df['vol_ratio_21_63'] = df['rv_21d'] / df['rv_63d']

    # Momentum features
    for w in [5, 10, 21, 63, 126, 252]:
        df[f'mom_{w}d'] = np.log(close / close.shift(w))

    # Normalized momentum (z-score)
    for w in [21, 63, 252]:
        mom = np.log(close / close.shift(w))
        df[f'mom_z_{w}d'] = (mom - mom.rolling(252).mean()) / mom.rolling(252).std()

    # Mean reversion features
    for w in [5, 10, 21, 63]:
        sma = close.rolling(w).mean()
        df[f'dist_sma_{w}d'] = (close - sma) / sma

    # Bollinger Band position
    sma20 = close.rolling(20).mean()
    std20 = close.rolling(20).std()
    df['bb_position'] = (close - sma20) / (2 * std20)

    # RSI (Relative Strength Index)
    delta = close.diff()
    gain = delta.clip(lower=0)
    loss = (-delta).clip(lower=0)
    rs14 = gain.ewm(com=13, min_periods=14).mean() / loss.ewm(com=13, min_periods=14).mean()
    df['rsi_14'] = 100 - 100 / (1 + rs14)
    df['rsi_z'] = (df['rsi_14'] - 50) / 15

    # Higher-moment features
    for w in [21, 63]:
        rolling_r = df['ret_1d'].rolling(w)
        df[f'skew_{w}d'] = rolling_r.apply(lambda x: skew(x), raw=True)
        df[f'kurt_{w}d'] = rolling_r.apply(lambda x: kurtosis(x), raw=True)

    # Volume features
    df['vol_chg'] = np.log(volume / volume.shift(1))
    df['vol_ratio'] = volume / volume.rolling(21).mean()
    df['turnover_21d'] = (volume * close).rolling(21).mean()

    # Amihud illiquidity
    df['amihud'] = (df['ret_1d'].abs() / (volume * close)).rolling(21).mean()

    # Range-based vol (Parkinson, Garman-Klass)
    df['hl_range'] = np.log(high / low)
    df['pk_vol'] = df['hl_range'].rolling(21).mean() / (2 * np.sqrt(np.log(2)))

    # Garman-Klass estimator - corrected formulation to avoid taking negative values inside the square root
    u = np.log(high / opn)
    d = np.log(low / opn)
    c = np.log(close / opn)
    gk_inner = 0.5 * (u - d) ** 2 - (2 * np.log(2) - 1) * c ** 2
    df['gk_vol'] = np.sqrt(252 * gk_inner.rolling(21).mean().clip(lower=0))

    # Intraday structure
    df['open_gap'] = np.log(opn / close.shift(1))
    df['close_range'] = np.log(close / opn)
    df['hi_dist'] = np.log(high / close)
    df['lo_dist'] = np.log(close / low)

    # Autocorrelation features
    for lag in [1, 2, 5, 10]:
        df[f'autocorr_{lag}d'] = df['ret_1d'].rolling(21).corr(df['ret_1d'].shift(lag))

    df['target_ret'] = df['ret_1d'].shift(-1)
    df['target_sign'] = (df['target_ret'] > 0).astype(int)
    df['target_5d_ret'] = np.log(close.shift(-5) / close)

    return df.dropna()

# Create feature matrix
df_feats = create_features('SPY')
print(f"Feature matrix shape: {df_feats.shape}")
print(f"Number of features: {df_feats.shape[1] - 3}")
print("\nFeature list (first 20):")
print(list(df_feats.columns[:20]))

# Feature correlation with next-day return
feat_cols = [c for c in df_feats.columns if 'target' not in c]
correlations = df_feats[feat_cols].corrwith(df_feats['target_ret']).sort_values()

fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 8))
correlations.head(15).plot(kind='barh', ax=ax1, color='firebrick', alpha=0.8)
ax1.set_title("Most Negative Correlations with 1-Day Return")
correlations.tail(15).plot(kind='barh', ax=ax2, color='lightblue', alpha=0.8)
ax2.set_title("Most Positive Correlations with 1-Day Return")
plt.tight_layout()
plt.savefig("feature_correlations.pdf", dpi=150)
plt.show()

