# PART 2: HAWKES PROCESS SIMULATION AND ESTIMATION
#

def simulate_hawkes(mu, alpha, beta, T_max=100, seed=42):
    """Simulate a univariate Hawkes process up to time T_max."""
    np.random.seed(seed)
    events = []
    t = 0
    while t < T_max:
        # Compute intensity at current time
        lambda_t = mu + sum(alpha * np.exp(-beta * (t - ti)) for ti in events if ti < t)
        # Upper bound on intensity
        lambda_bar = lambda_t
        # Generate candidate next event time (Ogata thinning)
        s = np.random.exponential(1 / max(lambda_bar, 1e-10))
        t = t + s
        if t >= T_max:
            break
        # Compute actual intensity at t
        lambda_actual = mu + sum(alpha * np.exp(-beta * (t - ti)) for ti in events if ti < t)
        # Accept/reject
        if np.random.uniform() <= lambda_actual / lambda_bar:
            events.append(t)
    return np.array(events)

def hawkes_loglik(params, events, T):
    """Log-likelihood of a Hawkes process given observed events."""
    mu, alpha, beta = params
    if mu <= 0 or alpha < 0 or beta <= 0 or alpha >= beta:
        return 1e10
    n = len(events)
    if n == 0:
        return mu * T
    # Integral = mu*T + alpha/beta * sum(1 - exp(-beta*(T - t_i)))
    integral = mu * T + (alpha / beta) * np.sum(1 - np.exp(-beta * (T - events)))
    # Intensities at event times
    log_lambda_sum = 0
    for i, t_i in enumerate(events):
        lam_i = mu + alpha * np.sum(np.exp(-beta * (t_i - events[:i])))
        if lam_i <= 0:
            return 1e10
        log_lambda_sum += np.log(lam_i)
    return -(log_lambda_sum - integral)

# Simulate Hawkes events
TRUE_MU = 0.5
TRUE_ALPHA = 0.8
TRUE_BETA = 1.5
T_MAX = 200

events_sim = simulate_hawkes(TRUE_MU, TRUE_ALPHA, TRUE_BETA, T_MAX)
print(f"\nSimulated {len(events_sim)} Hawkes events in [0, {T_MAX}]")
print(f"Average rate: {len(events_sim)/T_MAX:.3f} events/unit time")
print(f"Expected rate (mu/(1-n)): {TRUE_MU/(1 - TRUE_ALPHA/TRUE_BETA):.3f}")

# MLE Estimation
opt = minimize(
    hawkes_loglik,
    x0=[0.3, 0.5, 1.0],
    args=(events_sim, T_MAX),
    method='L-BFGS-B',
    bounds=[(1e-6, None), (0, None), (1e-4, None)],
    options={'maxiter': 2000}
)

mu_hat, alpha_hat, beta_hat = opt.x
n_hat = alpha_hat / beta_hat

print(f"\nHawkes MLE Estimates:")
print(f" True: mu={TRUE_MU:.3f}, alpha={TRUE_ALPHA:.3f}, beta={TRUE_BETA:.3f}, n={TRUE_ALPHA/TRUE_BETA:.3f}")
print(f" Estimated: mu={mu_hat:.3f}, alpha={alpha_hat:.3f}, beta={beta_hat:.3f}, n={n_hat:.3f}")
print(f"\nBranching ratio n={n_hat:.4f} {'(stationary: n<1)' if n_hat < 1 else '(CRITICAL: n>=1, NON-STATIONARY)'}")

# Visualize Hawkes process
ax3 = axes[1, 0]
t_grid = np.linspace(0, T_MAX, 2000)
lambda_grid = np.zeros(len(t_grid))
for i, t in enumerate(t_grid):
    lambda_grid[i] = mu_hat + alpha_hat * np.sum(np.exp(-beta_hat * (t - events_sim[events_sim < t])))

ax3.plot(t_grid, lambda_grid, 'firebrick', lw=1, label='Estimated L(t)')
ax3.vlines(events_sim, 0, 0.1, color='navy', lw=0.5, alpha=0.5, label='Events')
ax3.axhline(TRUE_MU, color='gray', lw=1, linestyle='--', label=f'Baseline={TRUE_MU}')
ax3.set_title(f"Hawkes Process Intensity: mu={mu_hat:.3f}, alpha={alpha_hat:.3f}, beta={beta_hat:.3f}")
ax3.set_xlabel("Time")
ax3.set_ylabel("Intensity L(t)")
ax3.legend(fontsize=8)

# Inter-event duration distribution
durations = np.diff(events_sim)
ax4 = axes[1, 1]
ax4.hist(durations, bins=50, density=True, color='steelblue', alpha=0.7, edgecolor='none', label='Observed')
x_range = np.linspace(0, np.quantile(durations, 0.99), 200)

# Exponential fit (null: Poisson)
exp_rate = 1.0 / durations.mean()
ax4.plot(x_range, expon.pdf(x_range, scale=1/exp_rate), 'r-', lw=2, label=f'Exponential (rate={exp_rate:.3f})')
ax4.set_title("Inter-Event Duration Distribution\n(Hawkes vs Poisson)")
ax4.set_xlabel("Duration")
ax4.set_ylabel("Density")
ax4.legend()

# KS test: are durations exponential (Poisson)?
from scipy.stats import kstest
ks_stat, ks_p = kstest(durations, expon(scale=1/exp_rate).cdf)
print(f"\nKS Test (Exponential null): stat={ks_stat:.4f}, p={ks_p:.4f}")
print(f" {'Reject Poisson (clustering present)' if ks_p < 0.05 else 'Cannot reject Poisson'}")

