import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import pandas_datareader as pdr
from statsmodels.tsa.statespace.sarimax import SARIMAX
from statsmodels.tsa.stattools import adfuller
import warnings
warnings.filterwarnings('ignore')

# Data: predict CPI inflation using M2, unemployment, oil
fred_series = {
    'CPI': 'CPIAUCSL',       # Consumer Price Index (monthly)
    'M2': 'M2SL',           # M2 money supply
    'UNEMP': 'UNRATE',       # Unemployment rate
    'OIL': 'DCOILWTICO',     # WTI crude oil (weekly -> monthly average)
    'FED': 'FEDFUNDS',       # Federal funds rate
}

data = pdr.get_data_fred(list(fred_series.values()), start='1985-01-01', end='2024-01-01')
data.columns = list(fred_series.keys())
data = data.resample('MS').last().dropna()

# Transformations
df = pd.DataFrame()
df['cpi_inf'] = np.log(data['CPI']).diff(12) * 100       # YoY inflation
df['m2_growth'] = np.log(data['M2']).diff(12) * 100     # YoY M2 growth
df['unemp'] = data['UNEMP']
df['oil_inf'] = np.log(data['OIL']).diff(12).fillna(0) * 100
df['fed_rate'] = data['FED']
df = df.dropna()

print(f"ARIMAX dataset: {df.shape}")
print(df.describe())

# Unit root tests
print("\nUnit Root Tests:")
for col in df.columns:
    p = adfuller(df[col], autolag='BIC')[1]
    print(f"  {col:<15}: p={p:.4f} ({'I(0)' if p<0.05 else 'I(1)?'})")

# Train / test split
n_test = 36  # last 3 years out-of-sample
train = df.iloc[:-n_test]
test = df.iloc[-n_test:]

y_train = train['cpi_inf']
y_test = test['cpi_inf']
X_train = train[['m2_growth', 'unemp', 'oil_inf', 'fed_rate']]
X_test = test[['m2_growth', 'unemp', 'oil_inf', 'fed_rate']]

# Model 1: ARIMA(2,0,2) without exogenous
arima_fit = SARIMAX(y_train, order=(2,0,2), trend='c').fit(disp=False)

# Model 2: ARIMAX(2,0,2) with exogenous
arimax_fit = SARIMAX(y_train, exog=X_train, order=(2,0,2), trend='c').fit(disp=False)

# Model 3: SARIMA(1,0,1)(1,0,1)_12 (seasonal)
sarima_fit = SARIMAX(y_train, order=(1,0,1), seasonal_order=(1,0,1,12), trend='c').fit(disp=False)

print("\nModel Comparison:")
print(f"  ARIMA(2,0,2):  AIC={arima_fit.aic:.2f}, BIC={arima_fit.bic:.2f}")
print(f"  ARIMAX(2,0,2): AIC={arimax_fit.aic:.2f}, BIC={arimax_fit.bic:.2f}")
print(f"  SARIMA(1,1)(1,1): AIC={sarima_fit.aic:.2f}, BIC={sarima_fit.bic:.2f}")
print(arimax_fit.summary())

# Out-of-sample forecasting
# 1-step ahead rolling forecasts
def rolling_forecast_arimax(order, exog_train, exog_test, y_train, y_test):
    """Rolling 1-step-ahead ARIMAX forecast."""
    preds = []
    for i in range(len(y_test)):
        y_tr = pd.concat([y_train, y_test.iloc[:i]])
        if exog_train is not None:
            X_tr = pd.concat([exog_train, exog_test.iloc[:i]])
            X_te = exog_test.iloc[[i]]
            fit = SARIMAX(y_tr, exog=X_tr, order=order, trend='c').fit(disp=False)
            fc = fit.forecast(steps=1, exog=X_te)
        else:
            fit = SARIMAX(y_tr, order=order, trend='c').fit(disp=False)
            fc = fit.forecast(steps=1)
        preds.append(fc.values[0])
    return np.array(preds)

print("\nComputing rolling out-of-sample forecasts...")
preds_arima = rolling_forecast_arimax((2,0,2), None, None, y_train, y_test)
preds_arimax = rolling_forecast_arimax((2,0,2), X_train, X_test, y_train, y_test)

# Metrics
from sklearn.metrics import mean_squared_error, mean_absolute_error
valid = ~(np.isnan(preds_arima) | np.isnan(y_test.values))
print("\nOut-of-Sample (Last 36 Months):")
print(f"  {'Model':<20} {'RMSE':>8} {'MAE':>8}")
for name, preds in [('ARIMA', preds_arima), ('ARIMAX', preds_arimax)]:
    if np.sum(valid) > 0:
        rmse = np.sqrt(mean_squared_error(y_test.values[valid], preds[valid]))
        mae = mean_absolute_error(y_test.values[valid], preds[valid])
        print(f"  {name:<20} {rmse:>8.4f} {mae:>8.4f}")

# Visualization
fig, axes = plt.subplots(3, 1, figsize=(14, 12))

# Panel 1: Full history + forecasts
axes[0].plot(y_train.index, y_train.values, 'navy', lw=1, label='Training')
axes[0].plot(y_test.index, y_test.values, 'k-', lw=1.5, label='Actual (test)')
axes[0].plot(y_test.index, preds_arima, 'r--', lw=1.5, label='ARIMA forecast')
axes[0].plot(y_test.index, preds_arimax, 'g-', lw=1.5, label='ARIMAX forecast')
axes[0].axvline(y_test.index[0], color='k', lw=0.8, linestyle=':')
axes[0].set_title("CPI Inflation: ARIMA vs ARIMAX Forecasts", fontweight='bold')
axes[0].set_ylabel("YoY CPI Inflation (%)")
axes[0].legend()

# Panel 2: ARIMAX coefficients and significance
coef = arimax_fit.params
bse = arimax_fit.bse
tval = coef / bse
colors_coef = ['red' if abs(t) < 1.96 else 'green' for t in tval[2:6]]
axes[1].barh(X_train.columns, coef[2:6], xerr=1.96*bse[2:6], color=colors_coef, alpha=0.7, edgecolor='k')
axes[1].axvline(0, color='k', lw=1)
axes[1].set_title("ARIMAX Coefficients (Green = significant at 5%)")
axes[1].set_xlabel("Coefficient Value")

# Panel 3: Residual diagnostics
resid = arimax_fit.resid
axes[2].plot(resid.index, resid.values, 'purple', lw=0.7, alpha=0.7)
axes[2].axhline(0, color='k', lw=0.5)
axes[2].set_title("ARIMAX Residuals")
axes[2].set_ylabel("Residual")

plt.tight_layout()
plt.savefig("arimax_cpi_forecast.pdf", dpi=150)
plt.show()

