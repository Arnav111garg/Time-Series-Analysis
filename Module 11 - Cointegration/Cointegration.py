# Johansen cointegration: Pairs trading application
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from statsmodels.tsa.vector_ar.vecm import coint_johansen, VECM
from statsmodels.tsa.stattools import coint, adfuller
from statsmodels.regression.linear_model import OLS
from statsmodels.tools import add_constant
import warnings
warnings.filterwarnings('ignore')

# CASE STUDY 1 : XLF vs. XLK ( Financial vs Technology ETFs) - NOT cointegrated
# CASE STUDY 2 : KO vs PEP (Coca-Cola vs Pepsi) - possibly cointegrated
# CASE STUDY 3 : 10Y vs 2Y Treasury yields - cointegrated (yield spread)

def full_cointegration_analysis(tickers, names, start='2010-01-01', end='2024-01-01', period='1d'):
    print(f"\n{'='*70}")
    print(f"Cointegration Analysis: {names[0]} vs {names[1]}")
    print('='*70)

    data = yf.download(tickers, start=start, end=end, auto_adjust=False)["Adj Close"]
    data = data.dropna()
    log_data = np.log(data)
    Y1 = log_data.iloc[:, 0]
    Y2 = log_data.iloc[:, 1]

    # Step 1: Unit root tests
    print("\n[1] Unit Root Tests:")
    for y, name in zip([Y1, Y2], names):
        p_lev = adfuller(y, autolag='BIC')[1]
        p_dif = adfuller(y.diff().dropna(), autolag='BIC')[1]
        status = 'I(1)' if p_lev > 0.05 and p_dif < 0.05 else 'check'
        print(f"  {name:<15}: level p={p_lev:.4f}, diff p={p_dif:.4f} -> {status}")

    # Step 2: Engle-Granger cointegration test
    eg_stat, eg_pval, _ = coint(Y1, Y2, trend='c')
    print("\n[2] Engle-Granger Test:")
    print(f"  t-statistic: {eg_stat:.4f}, p-value: {eg_pval:.4f}")
    print(f"  Conclusion: {'Cointegrated (p<0.05)' if eg_pval < 0.05 else 'NOT cointegrated (p>=0.05)'}")

    # Step 3: Cointegrating Vector via OLS
    ols_fit = OLS(Y1, add_constant(Y2)).fit()
    beta_hat = ols_fit.params.iloc[1]
    mu_hat = ols_fit.params.iloc[0]
    spread = Y1 - mu_hat - beta_hat * Y2
    print("\n[3] Cointegrating Vector:")
    print(f"  beta = {beta_hat:.4f} (hedge ratio)")
    print(f"  Spread = {names[0]} - {mu_hat:.4f} - {beta_hat:.4f} * {names[1]}")
    print(f"  ADF on spread: p={adfuller(spread, autolag='BIC')[1]:.4f}")

    # Step 4: Johansen test
    print("\n[4] Johansen Test (p=1, trend='co'):")
    johansen = coint_johansen(log_data, det_order=0, k_ar_diff=2)
    print("  Eigenvalues: ", johansen.eig)
    print("  Trace stat:  ", johansen.lr1)
    print("  Trace crit (10%, 5%, 1%): ", johansen.cvt)
    print("  Cointegrating vectors (columns):")
    print(pd.DataFrame(johansen.evec, index=names, columns=[f'CV{i+1}' for i in range(len(names))]))

    # Step 5: Visualize spread
    spread_z = (spread - spread.mean()) / spread.std()
    fig, axes = plt.subplots(3, 1, figsize=(14, 10), sharex=False)

    axes[0].plot(Y1.index, Y1, 'navy', lw=0.8, label=names[0])
    axes[0].plot(Y2.index, mu_hat + beta_hat * Y2, 'r--', lw=0.8, label=f'{beta_hat:.2f} * {names[1]}')
    axes[0].legend()
    axes[0].set_title("Log Prices with Scaled Counterpart")

    axes[1].plot(spread.index, spread, color='purple', lw=0.8)
    axes[1].axhline(spread.mean(), color='k', lw=1, label='Mean')
    axes[1].axhline(spread.mean() + 2 * spread.std(), color='r', lw=0.8, linestyle='--', label='\u00b12 Std Dev')
    axes[1].axhline(spread.mean() - 2 * spread.std(), color='r', lw=0.8, linestyle='--')
    axes[1].legend()
    axes[1].set_title("Cointegrating Spread")

    axes[2].plot(spread_z.index, spread_z, color='darkorange', lw=0.6, alpha=0.7)
    axes[2].fill_between(spread_z.index, spread_z, where=(spread_z > 2), color='red', alpha=0.3, label='Short')
    axes[2].fill_between(spread_z.index, spread_z, where=(spread_z < -2), color='green', alpha=0.3, label='Long')
    axes[2].axhline(2, color='r', lw=0.8, linestyle='--')
    axes[2].axhline(-2, color='g', lw=0.8, linestyle='--')
    axes[2].axhline(0, color='k', lw=0.5)
    axes[2].legend()
    axes[2].set_title("Z-Score: Trading Signals (Long if < -2, Short if > +2)")

    plt.tight_layout()
    plt.savefig(f"coint_{'_'.join(names)}.pdf", dpi=150)
    plt.show()

    return spread, beta_hat

# Run on Coca-Cola vs Pepsi
spread_ko_pep, beta_ko_pep = full_cointegration_analysis(['KO', 'PEP'], ['KO', 'PEP'], start='2010-01-01')

# Full pairs trading backtest based on cointegration
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from statsmodels.regression.linear_model import OLS
from statsmodels.tools import add_constant

def pairs_trading_backtest(Y1, Y2, name1, name2, entry_z=2.0, exit_z=0.5, lookback_coint=252, tc_bps=5):
    """
    Rolling-window cointegration-based pairs trading.
    Re-estimates beta every day over a rolling `lookback_coint` day window.
    Entry: |z-score| > entry_z. Exit: |z-score| < exit_z.
    tc_bps: transaction cost in basis points per leg.
    """
    log1 = np.log(Y1)
    log2 = np.log(Y2)
    T = len(log1)

    results = []
    position = 0  # +1 = long spread, -1 = short spread, 0 = flat
    beta_rolling = np.full(T, np.nan)
    spread_rolling = np.full(T, np.nan)
    zscore_rolling = np.full(T, np.nan)
    pnl = np.zeros(T)

    for t in range(lookback_coint, T):
        # Re-estimate beta on rolling window
        window1 = log1.iloc[t - lookback_coint:t]
        window2 = log2.iloc[t - lookback_coint:t]
        reg = OLS(window1.values, add_constant(window2.values)).fit()
        beta = reg.params[1]
        mu = reg.params[0]

        spread = log1.iloc[t] - mu - beta * log2.iloc[t]
        spr_window = log1.iloc[t - lookback_coint:t].values - mu - beta * log2.iloc[t - lookback_coint:t].values
        z = (spread - spr_window.mean()) / (spr_window.std() + 1e-10)

        beta_rolling[t] = beta
        spread_rolling[t] = spread
        zscore_rolling[t] = z

        # Compute daily P&L
        if t > lookback_coint:
            # Long spread = long Y1, short beta * Y2
            ret1 = log1.iloc[t] - log1.iloc[t - 1]
            ret2 = log2.iloc[t] - log2.iloc[t - 1]
            spread_ret = ret1 - beta_rolling[t - 1] * ret2
            pnl[t] = position * spread_ret

        # Apply transaction costs on position changes
        prev_pos = position

        # Trading signal
        if position == 0:
            if z < -entry_z:
                position = 1  # long spread
            elif z > entry_z:
                position = -1  # short spread
        elif position == 1:
            if z > -exit_z:
                position = 0  # exit long
        elif position == -1:
            if z < exit_z:
                position = 0  # exit short

        if position != prev_pos:
            tc = tc_bps * 1e-4 * abs(position - prev_pos)
            pnl[t] -= tc

        results.append({
            't': t,
            'beta': beta,
            'spread': spread,
            'z': z,
            'pos': position,
            'pnl': pnl[t]
        })

    df = pd.DataFrame(results, index=log1.index[lookback_coint:])
    pnl_series = pd.Series(pnl[lookback_coint:], index=log1.index[lookback_coint:])
    cum_pnl = (1 + pnl_series).cumprod()

    # Performance metrics
    n_years = len(pnl_series) / 252
    ann_ret = pnl_series.mean() * 252
    ann_vol = pnl_series.std() * np.sqrt(252)
    sharpe = ann_ret / ann_vol if ann_vol > 0 else 0
    max_dd = (cum_pnl / cum_pnl.cummax() - 1).min()
    n_trades = (df['pos'].diff() != 0).sum()

    print(f"\n{'='*50}")
    print(f"Pairs Trading Backtest: {name1} vs {name2}")
    print(f"{'='*50}")
    print(f"Ann. Return    : {ann_ret * 100:+.2f}%")
    print(f"Ann. Volatility: {ann_vol * 100:.2f}%")
    print(f"Sharpe Ratio   : {sharpe:.3f}")
    print(f"Max Drawdown   : {max_dd * 100:.2f}%")
    print(f"Calmar Ratio   : {ann_ret / abs(max_dd) if max_dd != 0 else 0:.3f}")
    print(f"Num Trades     : {n_trades}")

    # Plotting
    fig, axes = plt.subplots(3, 1, figsize=(14, 10), sharex=True)
    axes[0].plot(df['z'], color='purple', lw=0.6)
    axes[0].axhline(entry_z, color='r', lw=0.8, linestyle='--')
    axes[0].axhline(-entry_z, color='g', lw=0.8, linestyle='--')
    axes[0].axhline(exit_z, color='r', lw=0.4, linestyle=':')
    axes[0].axhline(-exit_z, color='g', lw=0.4, linestyle=':')
    axes[0].axhline(0, color='k', lw=0.5)
    axes[0].set_title("Z-Score of Spread")
    axes[0].set_ylabel("Z-Score")

    axes[1].plot(df['pos'], color='navy', lw=0.8, drawstyle='steps-post')
    axes[1].set_ylim(-1.5, 1.5)
    axes[1].set_yticks([-1, 0, 1])
    axes[1].set_yticklabels(['Short', 'Flat', 'Long'])
    axes[1].set_title("Portfolio Position")

    axes[2].plot(cum_pnl.index, cum_pnl.values, color='darkgreen', lw=1.5)
    axes[2].axhline(1, color='k', lw=0.5, linestyle='--')
    axes[2].set_title(f"Cumulative P&L (Sharpe: {sharpe:.2f})")
    axes[2].set_ylabel("Wealth")

    plt.tight_layout()
    plt.savefig(f"pairs_backtest_{name1}_{name2}.pdf", dpi=150)
    plt.show()

    return df, pnl_series

