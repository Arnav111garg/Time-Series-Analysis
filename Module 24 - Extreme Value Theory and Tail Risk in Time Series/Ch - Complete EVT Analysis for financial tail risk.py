import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from scipy.stats import genpareto, genextreme, norm
from scipy.optimize import minimize
import warnings; warnings.filterwarnings('ignore')

# Download SPX data
data = yf.download("^GSPC", start="1990-01-01", end="2024-01-01")

# Safely handle both MultiIndex or flat columns
if isinstance(data.columns, pd.MultiIndex):
    if 'Adj Close' in data.columns.get_level_values(0):
        spx = data['Adj Close'].iloc[:, 0]
    else:
        spx = data['Close'].iloc[:, 0]
else:
    if 'Adj Close' in data.columns:
        spx = data['Adj Close']
    else:
        spx = data['Close']

r = 100 * np.log(spx / spx.shift(1)).dropna()
losses = -r.values # work with losses (positive = bad)
T = len(losses)
print(f"SPX daily losses: {T} observations ({r.index[0].date()} to {r.index[-1].date()})")
print(f"Sample statistics: mean={losses.mean():.4f}%, std={losses.std():.4f}%")
print(f"Max loss: {losses.max():.4f}% ({r.index[np.argmin(r.values)].date()})")

# STEP 1: MEAN EXCESS FUNCTION (THRESHOLD SELECTION)
def mean_excess_function(losses, u_range=None, min_exceedances=30):
    """Compute the mean excess function e(u) = E[X-u | X>u]."""
    losses_sorted = np.sort(losses)
    if u_range is None:
        u_range = np.linspace(losses_sorted[int(0.80*T)], losses_sorted[int(0.99*T)], 100)
    mef_u = []
    mef_e = []
    mef_se = []
    for u in u_range:
        exceedances = losses[losses > u] - u
        if len(exceedances) >= min_exceedances:
            mef_u.append(u)
            mef_e.append(exceedances.mean())
            mef_se.append(exceedances.std() / np.sqrt(len(exceedances)))
    return np.array(mef_u), np.array(mef_e), np.array(mef_se)

u_range, mef, mef_se = mean_excess_function(losses)

# STEP 2: HILL ESTIMATOR (TAIL INDEX)
def hill_estimator(losses, k_range=None):
    """Hill (1975) estimator of the tail index xi = 1/alpha."""
    sorted_losses = np.sort(losses)[::-1] # descending order
    n = len(sorted_losses)
    if k_range is None:
        k_range = np.arange(10, min(500, n//4))
    hill_xi = []
    for k in k_range:
        xi_k = np.mean(np.log(sorted_losses[:k]) - np.log(sorted_losses[k]))
        hill_xi.append(xi_k)
    return k_range, np.array(hill_xi)

k_range, hill_xi = hill_estimator(losses)

# Choose threshold: look for stability region
u_threshold = np.percentile(losses, 97.5)
print(f"\nSelected threshold: {u_threshold:.4f}% (97.5th percentile)")
n_exceed = np.sum(losses > u_threshold)
print(f"Number of exceedances: {n_exceed} ({n_exceed/T*100:.1f}%)")

# STEP 3: FIT GPD TO EXCEEDANCES
exceedances = losses[losses > u_threshold] - u_threshold

# MLE fit using scipy
xi_hat, loc_hat, sigma_hat = genpareto.fit(exceedances, floc=0)
print(f"\nGPD MLE fit:")
print(f" Shape xi (tail index): {xi_hat:.4f}")
print(f" Scale sigma: {sigma_hat:.4f}")
print(f" (xi > 0 = heavy tail; xi=0 = Gumbel; xi < 0 = bounded)")

# KS goodness-of-fit test
from scipy.stats import kstest
ks_stat, ks_p = kstest(exceedances, genpareto(xi_hat, loc=0, scale=sigma_hat).cdf)
print(f" KS test: stat={ks_stat:.4f}, p={ks_p:.4f} ({'Good fit' if ks_p>0.1 else 'Poor fit'})")

# STEP 4: EXTREME QUANTILE ESTIMATION
p_u = n_exceed / T # exceedance probability

def evt_var(p, u, sigma, xi, p_u):
    """EVT-based VaR at probability level p (1-p = confidence)."""
    if 1 - p < p_u:
        # Not in the tail
        return np.percentile(losses, (1 - p) * 100)
    return u + (sigma / xi) * ((p_u / (1 - p)) ** (-xi) - 1) if xi != 0 else u + sigma * np.log(p_u / (1 - p))

def evt_es(p, u, sigma, xi, p_u):
    """EVT-based Expected Shortfall at probability level p."""
    var = evt_var(p, u, sigma, xi, p_u)
    if xi >= 1:
        return np.inf
    return (var + sigma - xi * u) / (1 - xi)

# Historical VaR for comparison
def hist_var(p):
    return np.percentile(losses, (1 - p) * 100)

print(f"\n{'Probability Level': <22} {'EVT VaR': >10} {'Historical VaR': >15} {'Gaussian VaR': >13}")
print('-' * 62)
for conf_level in [0.95, 0.99, 0.995, 0.999, 0.9999]:
    p = 1 - conf_level
    var_evt = evt_var(p, u_threshold, sigma_hat, xi_hat, p_u)
    var_his = hist_var(p) if conf_level < 0.999 else np.nan
    var_gau = -norm.ppf(p, loc=losses.mean(), scale=losses.std())
    es_evt = evt_es(p, u_threshold, sigma_hat, xi_hat, p_u)
    print(f" {conf_level * 100:.2f}% {var_evt:>+8.3f}% {var_his:>+12.3f}% {var_gau:>+11.3f}%")

# STEP 5: VISUALIZATION
fig, axes = plt.subplots(2, 3, figsize=(16, 10))
fig.suptitle("Extreme Value Theory Analysis: SPX Daily Losses (1990-2024)", fontsize=13, fontweight='bold')

# 1. MEF plot
axes[0, 0].plot(u_range, mef, 'navy', lw=1.5)
axes[0, 0].fill_between(u_range, mef - 1.96 * mef_se, mef + 1.96 * mef_se, alpha=0.2, color='navy')
axes[0, 0].axvline(u_threshold, color='red', lw=2, linestyle='--', label=f'Threshold = {u_threshold:.2f}%')
axes[0, 0].set_xlabel("Threshold u (%)"); axes[0, 0].set_ylabel("Mean Excess e(u) (%)")
axes[0, 0].set_title("Mean Excess Function\n(Linear region GPD)")
axes[0, 0].legend()

# 2. Hill plot
axes[0, 1].plot(k_range, hill_xi, 'firebrick', lw=1.2)
axes[0, 1].axhline(xi_hat, color='k', lw=1.5, linestyle='--', label=f'GPD = {xi_hat:.3f}')
axes[0, 1].set_xlabel("k (number of upper order statistics)")
axes[0, 1].set_ylabel("Hill estimator (k)")
axes[0, 1].set_title("Hill Plot (Tail Index Stability)")
axes[0, 1].legend()

# 3. GPD QQ-plot
sorted_exc = np.sort(exceedances)
n_exc = len(sorted_exc)
probs = (np.arange(1, n_exc + 1) - 0.5) / n_exc
theoretical = genpareto.ppf(probs, c=xi_hat, loc=0, scale=sigma_hat)
axes[0, 2].scatter(theoretical, sorted_exc, s=8, alpha=0.5, color='steelblue')
max_val = max(theoretical.max(), sorted_exc.max())
axes[0, 2].plot([0, max_val], [0, max_val], 'r-', lw=1.5, label='45° line')
axes[0, 2].set_xlabel("Theoretical GPD Quantiles")
axes[0, 2].set_ylabel("Empirical Quantiles")
axes[0, 2].set_title(f"GPD Q-Q Plot\n={xi_hat:.3f}, ={sigma_hat:.3f}")
axes[0, 2].legend()

# 4. Loss distribution with tail fit
losses_sorted = np.sort(losses)
ecdf = np.arange(1, T + 1) / T
tail_mask = losses_sorted >= u_threshold
x_tail = np.linspace(u_threshold, losses.max() * 1.2, 200)
# EVT CDF
cdf_evt = 1 - p_u * (1 + xi_hat * (x_tail - u_threshold) / sigma_hat) ** (-1 / xi_hat)
# Gaussian CDF
cdf_gau = norm.cdf(x_tail, loc=losses.mean(), scale=losses.std())

axes[1, 0].semilogy(losses_sorted, 1 - ecdf, 'navy', lw=1.5, label='Empirical')
axes[1, 0].semilogy(x_tail, 1 - cdf_evt, 'red', lw=2, linestyle='--', label=f'GPD tail fit (={xi_hat:.3f})')
axes[1, 0].semilogy(x_tail, 1 - cdf_gau, 'green', lw=2, linestyle=':', label='Gaussian fit')
axes[1, 0].axvline(u_threshold, color='k', lw=0.8, linestyle=':', label='Threshold')
axes[1, 0].set_xlabel("Loss (%)"); axes[1, 0].set_ylabel("P(Loss > x) [log scale]")
axes[1, 0].set_title("Tail Probability: EVT vs Gaussian")
axes[1, 0].legend(fontsize=8)
axes[1, 0].set_xlim(0, losses.max() * 1.1)

# 5. VaR backtest
from scipy.stats import binom
# Rolling 1Y EVT-VaR
alpha_bt = 0.99
var_rolling = pd.Series(np.nan, index=r.index)
window_bt = 252

for t in range(window_bt + 1, T):
    loss_win = losses[t - window_bt:t]
    u_t = np.percentile(loss_win, 97.5)
    exc_t = loss_win[loss_win > u_t] - u_t
    if len(exc_t) < 5:
        var_rolling.iloc[t] = np.percentile(loss_win, alpha_bt * 100)
        continue
    try:
        xi_t, _, sig_t = genpareto.fit(exc_t, floc=0)
        pu_t = np.sum(loss_win > u_t) / window_bt
        var_t = evt_var(1 - alpha_bt, u_t, sig_t, xi_t, pu_t)
        var_rolling.iloc[t] = var_t
    except Exception:
        var_rolling.iloc[t] = np.percentile(loss_win, alpha_bt * 100)

var_rolling = var_rolling.dropna()
# Slicing the alignment-safe series -r instead of the numpy array losses
violations = -r[var_rolling.index] > var_rolling.values
viol_rate = violations.mean()
expected_rate = 1 - alpha_bt

print(f"\nVaR Backtest (99% EVT-VaR, Rolling 1Y):")
print(f" Expected violation rate: {expected_rate * 100:.2f}%")
print(f" Actual violation rate: {viol_rate * 100:.2f}%")
binom_p = binom.sf(violations.sum() - 1, len(violations), expected_rate)
print(f" Kupiec LR test p-value: {binom_p:.4f} ({'Pass' if binom_p>0.05 else 'Fail'})")

axes[1, 1].plot(r.index[window_bt:], -r[window_bt:], 'gray', lw=0.5, alpha=0.6, label='Daily Loss')
axes[1, 1].plot(var_rolling.index, var_rolling.values, 'red', lw=1.2, label='99% EVT-VaR')
viol_dates = var_rolling.index[violations]
axes[1, 1].scatter(viol_dates, -r[var_rolling.index][violations], color='red', s=15, zorder=5, label=f'Violations ({viol_rate * 100:.1f}%)')
axes[1, 1].set_title("VaR Backtest: 99% EVT Rolling VaR")
axes[1, 1].set_ylabel("Loss (%)")
axes[1, 1].legend(fontsize=8)

# 6. Annual block maxima distribution
annual_max = pd.Series(losses, index=r.index).resample('YE').max().dropna()
xi_bm, loc_bm, scale_bm = genextreme.fit(-annual_max.values)
xi_bm = -xi_bm

x_bm = np.linspace(annual_max.min() * 0.9, annual_max.max() * 1.5, 200)
gev_pdf = genextreme.pdf(-x_bm, c=-xi_bm, loc=loc_bm, scale=scale_bm)

axes[1, 2].hist(-annual_max.values, bins=15, density=True, color='steelblue', alpha=0.7, edgecolor='none', label='Annual maxima')
axes[1, 2].plot(x_bm, gev_pdf, 'red', lw=2.5, label=f'GEV fit (={xi_bm:.3f})')
axes[1, 2].set_xlabel("Annual Maximum Loss (%)")
axes[1, 2].set_title(f"Block Maxima: GEV Fit (={xi_bm:.3f})")
axes[1, 2].legend()

