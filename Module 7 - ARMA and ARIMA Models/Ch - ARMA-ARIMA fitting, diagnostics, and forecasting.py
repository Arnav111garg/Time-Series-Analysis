import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from statsmodels.tsa.statespace.sarimax import SARIMAX
from statsmodels.tsa.arima.model import ARIMA
from statsmodels.tsa.stattools import adfuller
from statsmodels.graphics.tsaplots import plot_acf, plot_pacf
from statsmodels.stats.diagnostic import acorr_ljungbox
from sklearn.metrics import mean_squared_error
import warnings
warnings.filterwarnings('ignore')

# Alternative to FRED: download 10-Year Treasury Yield (^TNX) from yfinance
tnx_df = yf.download('^TNX', start='1980-01-01', end='2024-01-01')
tnx_series = tnx_df['Close'].squeeze().dropna()

# Reset index to avoid index frequency issues in statsmodels
tnx = tnx_series.reset_index(drop=True)

# Step 1: Identify d
print("ADF on levels:", adfuller(tnx)[1]) # likely > 0.05
print("ADF on 1st diff:", adfuller(tnx.diff().dropna())[1]) # likely < 0.05

# Step 2: Identify p, q from ACF/PACF of differenced series
d1_tnx = tnx.diff().dropna()

fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 4))
plot_acf(d1_tnx, lags=24, ax=ax1, title="ACF: $\\Delta$ TNX")
plot_pacf(d1_tnx, lags=24, ax=ax2, title="PACF: $\\Delta$ TNX", method='ywm')
plt.tight_layout()
plt.savefig("tnx_acf_pacf.pdf", dpi=150)

# Step 3: Fit candidate models
results = {}
for p in range(0, 4):
    for q in range(0, 4):
        try:
            mdl = ARIMA(tnx, order=(p, 1, q)).fit()
            results[(p, q)] = {'AIC': mdl.aic, 'BIC': mdl.bic, 'LogL': mdl.llf, 'model': mdl}
        except Exception:
            pass

aic_df = pd.DataFrame({k: v for k, v in results.items() if 'AIC' in v}).T[['AIC', 'BIC', 'LogL']]
aic_df.index.names = ['p', 'q']
print("\nModel Comparison:")
print(aic_df.sort_values('BIC').head(10))

best_pq = aic_df['BIC'].idxmin()
best_model = results[best_pq]['model']
print(f"\nBest model (BIC): ARIMA{(best_pq[0], 1, best_pq[1])}")
print(best_model.summary())

# Step 4: Residual diagnostics
resid = best_model.resid.dropna()
fig, axes = plt.subplots(2, 2, figsize=(12, 8))
resid.plot(ax=axes[0, 0], title='Residuals')
plot_acf(resid, lags=20, ax=axes[0, 1], title='ACF of Residuals')
pd.Series(resid).hist(bins=40, ax=axes[1, 0])
axes[1, 0].set_title('Residuals Histogram')
from scipy import stats
stats.probplot(resid, dist='norm', plot=axes[1, 1])
axes[1, 1].set_title('Q-Q Plot')
plt.tight_layout()
plt.savefig("arima_diagnostics.pdf", dpi=150)

lb = acorr_ljungbox(resid, lags=[10, 20], return_df=True)
print(f"\nLjung-Box p-values: {lb['lb_pvalue'].values}")

# Step 5: Rolling forecast evaluation
n_test = 24  # last 24 months out-of-sample
train = tnx.iloc[:-n_test]
test = tnx.iloc[-n_test:]

preds = []
for i in range(n_test):
    # Re-fit the ARIMA model with integer-indexed data to avoid datetime index issues
    current_train = tnx.iloc[:len(train) + i]
    mdl = ARIMA(current_train, order=(int(best_pq[0]), 1, int(best_pq[1]))).fit()
    preds.append(mdl.forecast(1).values[0])

rmse = np.sqrt(mean_squared_error(test, preds))
print(f"\nRolling 1-step forecast RMSE: {rmse:.4f} percentage points")

